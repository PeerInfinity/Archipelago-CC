#!/usr/bin/env python3
"""Extract the Metamath token -> Unicode symbol map from set.mm's $t block.

set.mm ships its own authoritative typesetting definitions in a `$t` comment as
`althtmldef "token" as '<html>';` entries (the HTML/Unicode used by the official
site). We parse those, reduce each to a plain Unicode string, and emit a small JS
module the frontend proof panels use to render expressions like
`|- ( 2 + 2 ) = 4` as `⊢ ( 2 + 2 ) = 4`.

Identity mappings (token renders as itself, e.g. `Vtx`, `(`, digits) are omitted —
the renderer falls back to the raw token, so they need no entry.

Usage:
    python scripts/data/extract_metamath_symbols.py \
        [--set-mm metamath_data/set.mm] \
        [--out frontend/modules/proofShared/metamathSymbols.js]
"""
import argparse
import html
import os
import re

DEFAULT_SET_MM = "metamath_data/set.mm"
DEFAULT_OUT = "frontend/modules/proofShared/metamathSymbols.js"

# A quoted string in the $t mini-language: single- or double-quoted.
_QSTR = r"(?:\"[^\"]*\"|'[^']*')"
# althtmldef "<token>" as <one-or-more quoted strings> ;
_ENTRY = re.compile(
    r"althtmldef\s+(" + _QSTR + r")\s+as\s+((?:" + _QSTR + r"|\s)+);",
    re.DOTALL,
)
_TAG = re.compile(r"<[^>]+>")
_COMMENT = re.compile(r"/\*.*?\*/", re.DOTALL)


def _unquote_concat(raw: str) -> str:
    """Concatenate the contents of one or more adjacent quoted strings."""
    parts = re.findall(_QSTR, raw, re.DOTALL)
    return "".join(p[1:-1] for p in parts)


def _to_unicode(html_value: str) -> str:
    """Strip HTML tags, decode entities, collapse whitespace to a plain string."""
    text = _TAG.sub("", html_value)
    text = html.unescape(text)
    # Many entries pad with spaces (e.g. ' &isin; '); normalise to a bare symbol.
    return " ".join(text.split())


def extract(set_mm_path: str) -> dict:
    with open(set_mm_path, encoding="utf-8") as f:
        text = f.read()

    # Restrict to the $t typesetting block to avoid matching prose.
    start = text.find("$t")
    if start != -1:
        text = text[start:]
    # Drop $t-level /* ... */ comments (incl. commented-out althtmldef lines).
    text = _COMMENT.sub("", text)

    symbols = {}
    for tok_raw, val_raw in _ENTRY.findall(text):
        token = _unquote_concat(tok_raw)
        rendered = _to_unicode(_unquote_concat(val_raw))
        # Skip empties and identity mappings — the renderer keeps the raw token.
        if rendered and rendered != token:
            symbols[token] = rendered
    return symbols


def write_js(symbols: dict, out_path: str) -> None:
    lines = [
        "// AUTO-GENERATED by scripts/data/extract_metamath_symbols.py — do not edit by hand.",
        "// Maps Metamath ASCII tokens to Unicode symbols (from set.mm's $t althtmldef block).",
        "// Regenerate after a set.mm update: python scripts/data/extract_metamath_symbols.py",
        "export const METAMATH_SYMBOLS = {",
    ]
    for token in sorted(symbols):
        tok = token.replace("\\", "\\\\").replace('"', '\\"')
        sym = symbols[token].replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'  "{tok}": "{sym}",')
    lines.append("};")
    lines.append("")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--set-mm", default=DEFAULT_SET_MM)
    ap.add_argument("--out", default=DEFAULT_OUT)
    args = ap.parse_args()

    symbols = extract(args.set_mm)
    write_js(symbols, args.out)
    print(f"Extracted {len(symbols)} non-identity symbol mappings -> {args.out}")
    # Spot-check a few well-known tokens.
    for t in ["|-", "->", "e.", "A.", "E.", "CC", "RR", "/\\", "ph", "(/)", "-."]:
        print(f"  {t!r:8} -> {symbols.get(t, '(identity/none)')!r}")


if __name__ == "__main__":
    main()
