    --script)
      SCRIPT_MODE=true
      OUTPUT_SCRIPT="${2:?Error: --script requires an output file path}"
      shift 2
      ;;
    --help|-h)
      usage
      exit 0
      ;;
    *)
      echo "Unknown argument: $1" >&2
      usage >&2
      exit 1
      ;;
  esac
done

