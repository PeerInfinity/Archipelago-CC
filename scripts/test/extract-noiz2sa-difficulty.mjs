/**
 * Extract the Noiz2sa difficulty table the generation-time pricing reads (bulletml N5):
 *
 *   frontend/modules/noiz2saSubstrate/noiz2saDifficultyData.js
 *
 * from the game repo's measured segment sweeps (`results/segments-scenes.json`, `segments-top.json`,
 * `segments-triples.json` of `PeerInfinity/bulletml-dodge`, all on the centered hitbox, game seed 1, 16 bot seeds).
 * The three files are 48 MB together and only `{n, deathless, L, F}` per span × skill is needed, so the table keeps
 * exactly that: every scene of stages 1–10 and every aligned three-scene span, at the skills the sweeps measured
 * (0–80 step 10 from the scene and triple sweeps; 90, 92, 94, 96, 98, 99, 100 from the top sweep — its 90 and 100
 * are the same runs as the other two files' 90 and 100, checked here).
 *
 * The files are read from the submodule's checkout (`frontend/modules/bulletml-dodge/results/`), pinned at a commit
 * that carries all three sweeps (19e3de1); the table records the submodule's commit.
 *
 *   node scripts/test/extract-noiz2sa-difficulty.mjs                 # write the table
 *   node scripts/test/extract-noiz2sa-difficulty.mjs --check         # exit 1 when the committed table differs
 */

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '../..');
const SUBMODULE = path.join(repoRoot, 'frontend/modules/bulletml-dodge');
const OUT = path.join(repoRoot, 'frontend/modules/noiz2saSubstrate/noiz2saDifficultyData.js');

const check = process.argv.slice(2).includes('--check');

const commit = execFileSync('git', ['-C', SUBMODULE, 'rev-parse', '--short=7', 'HEAD'], { encoding: 'utf8' }).trim();
const read = (name) => JSON.parse(fs.readFileSync(path.join(SUBMODULE, 'results', name), 'utf8'));

const scenes = read('segments-scenes.json');
const top = read('segments-top.json');
const triples = read('segments-triples.json');

const LOW = [0, 10, 20, 30, 40, 50, 60, 70, 80];
const HIGH = [90, 92, 94, 96, 98, 99, 100];
const SKILLS = [...LOW, ...HIGH];

const bySpan = (doc) => new Map(doc.spans.map((s) => [s.span, s]));
const S = bySpan(scenes); const T = bySpan(top); const R = bySpan(triples);

const r3 = (x) => (Number.isFinite(x) ? Math.round(x * 1000) / 1000 : null);
/** one measured cell → [n, deathless, L, F] (L null when no attempt was deathless, F null when none failed) */
function cell(entry, skill) {
    const c = entry?.players?.[`skill ${skill}`];
    if (!c) throw new Error(`no "skill ${skill}" for ${entry?.span}`);
    return [c.n, c.deathless, c.deathless > 0 ? r3(c.L) : null, c.n - c.deathless > 0 ? r3(c.F) : null];
}
const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);

function rows(lowDoc, span) {
    const lo = lowDoc.get(span); const hi = T.get(span);
    if (!lo || !hi) throw new Error(`span ${span} missing (low ${!!lo}, top ${!!hi})`);
    for (const k of [90, 100]) {
        if (!same(cell(lo, k), cell(hi, k))) throw new Error(`${span} skill ${k}: the top sweep is not the same runs`);
    }
    return [...LOW.map((k) => cell(lo, k)), ...HIGH.map((k) => cell(hi, k))];
}

const sceneSpans = scenes.spans.map((s) => s.span);
if (sceneSpans.length !== 100) throw new Error(`expected 100 scenes, got ${sceneSpans.length}`);
const tripleSpans = triples.spans.map((s) => s.span).filter((s) => s.includes('–'));

const table = {
    source: {
        repo: 'PeerInfinity/bulletml-dodge',
        commit,
        files: ['results/segments-scenes.json', 'results/segments-top.json', 'results/segments-triples.json'],
        hitbox: scenes.meta.signature.hitbox,
        gameSeeds: scenes.meta.signature.seeds,
        botSeeds: scenes.meta.signature.botSeeds.length,
    },
    skills: SKILLS,
    cell: ['n', 'deathless', 'L', 'F'],
    scenes: Object.fromEntries(sceneSpans.map((s) => [s, rows(S, s)])),
    triples: Object.fromEntries(tripleSpans.map((s) => [s, rows(R, s)])),
};

const body = Object.entries({ scenes: table.scenes, triples: table.triples }).map(([k, m]) => `    ${k}: {\n${
    Object.entries(m).map(([s, rs]) => `        '${s}': ${JSON.stringify(rs)},`).join('\n')}\n    },`).join('\n');
const text = `/**
 * GENERATED by scripts/test/extract-noiz2sa-difficulty.mjs — do not edit by hand.
 *
 * The humanlike bot's measured difficulty of every Noiz2sa scene (stages 1–10) and every aligned three-scene span, at
 * each measured skill (equal tracks = the skill slider): per cell [n, deathless, L, F] — the attempts (one per bot
 * seed), the deathless ones, a clean clear's mean seconds (null: none was clean) and a failed attempt's mean seconds
 * (null: none failed). Source: ${table.source.repo} @ ${commit}, ${table.source.files.join(', ')}; hitbox
 * ${table.source.hitbox}, game seed ${table.source.gameSeeds.join(', ')}, ${table.source.botSeeds} bot seeds. Read by
 * \`noiz2saDifficulty.js\`.
 */
export const NOIZ2SA_DIFFICULTY = Object.freeze({
    source: ${JSON.stringify(table.source)},
    skills: ${JSON.stringify(table.skills)},
    cell: ${JSON.stringify(table.cell)},
${body}
});
`;

if (check) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (now !== text) { console.log(`FAIL: ${path.relative(repoRoot, OUT)} differs from the submodule's results (${commit})`); process.exit(1); }
    console.log(`PASS: ${path.relative(repoRoot, OUT)} matches the submodule's results (${commit})`);
} else {
    fs.writeFileSync(OUT, text);
    console.log(`wrote ${path.relative(repoRoot, OUT)}: ${sceneSpans.length} scenes, ${tripleSpans.length} triples × ${SKILLS.length} skills, from ${commit}`);
}
