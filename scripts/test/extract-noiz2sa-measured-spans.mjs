/**
 * Extract the Noiz2sa MEASURED SPANS the difficulty model reads beside the game repo's sweeps (bulletml N5):
 *
 *   scripts/data/noiz2sa-measured-spans.json      (the aggregates, with provenance — the committed source)
 *   frontend/modules/noiz2saSubstrate/noiz2saMeasuredSpansData.js   (generated from it)
 *
 * A measured span is one the sweeps' 16-seed table reads badly: the default final span 10:7–10:boss was ≈ 2×
 * optimistic at skills 95–97 as a product of its four scenes (CC/docs/cloud-reports/noiz2sa-difficulty-optimism.md). Its cells come from
 * `measure-noiz2sa-grid.mjs` (the page's visit: restart on a hit, equal tracks at the skill, observed perception,
 * centered hitbox, game seed 1), at every skill it was measured at (at least the table's ends, 0 and 100): the bot's
 * curve there is step-shaped (flat 93–95, a jump 97 → 98), so the model reads a measured span on ITS OWN skills.
 *
 *   node scripts/test/extract-noiz2sa-measured-spans.mjs --from grid1.json [grid2.json …]   # aggregate + write both
 *   node scripts/test/extract-noiz2sa-measured-spans.mjs                                   # rewrite the module from the json
 *   node scripts/test/extract-noiz2sa-measured-spans.mjs --check                           # exit 1 when the module differs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '../..');
const SRC = path.join(repoRoot, 'scripts/data/noiz2sa-measured-spans.json');
const OUT = path.join(repoRoot, 'frontend/modules/noiz2saSubstrate/noiz2saMeasuredSpansData.js');
const FPS = 62.5;
const args = process.argv.slice(2);
const r3 = (x) => (Number.isFinite(x) ? Math.round(x * 1000) / 1000 : null);

const { NOIZ2SA_DIFFICULTY } = await import(pathToFileURL(path.join(repoRoot, 'frontend/modules/noiz2saSubstrate/noiz2saDifficultyData.js')));

if (args.includes('--from')) {
    const files = args.slice(args.indexOf('--from') + 1).filter((a) => !a.startsWith('--'));
    const cells = files.flatMap((f) => JSON.parse(fs.readFileSync(f, 'utf8')).cells);
    const spans = {};
    for (const c of cells) {
        const att = c.visits.flat();
        const ok = att.filter((x) => x.c); const bad = att.filter((x) => !x.c);
        (spans[c.spanText] ??= {})[c.skill] = {
            n: att.length, deathless: ok.length,
            L: ok.length ? r3(ok.reduce((a, x) => a + x.f, 0) / ok.length / FPS) : null,
            F: bad.length ? r3(bad.reduce((a, x) => a + x.f, 0) / bad.length / FPS) : null,
            visits: c.visits.length, censored: c.visits.filter((v) => !v.at(-1).c).length, maxAttempts: c.maxAttempts,
        };
    }
    for (const [span, by] of Object.entries(spans)) {
        if (!by[0] || !by[100]) throw new Error(`${span}: needs cells at skills 0 and 100 (the model reads between its measured skills)`);
    }
    const doc = {
        about: 'Aggregated by scripts/test/extract-noiz2sa-measured-spans.mjs from measure-noiz2sa-grid.mjs runs; see CC/docs/cloud-reports/noiz2sa-difficulty-optimism.md',
        method: { tool: 'scripts/test/measure-noiz2sa-grid.mjs', bot: 'equal tracks at the skill, observed perception', hitbox: 'centered', gameSeed: 1,
            visit: 'restart on a hit; attempt a of visit v on attemptBotSeed(v, a)', gameCommit: NOIZ2SA_DIFFICULTY.source.commit },
        spans: Object.fromEntries(Object.entries(spans).map(([s, by]) => {
            const ks = Object.keys(by).map(Number).sort((a, b) => a - b);
            return [s, { skills: ks, cells: ks.map((k) => by[k]) }];
        })),
    };
    fs.mkdirSync(path.dirname(SRC), { recursive: true });
    fs.writeFileSync(SRC, JSON.stringify(doc, null, 2) + '\n');
    console.log(`wrote ${path.relative(repoRoot, SRC)}: ${Object.keys(spans).join(', ')}`);
}

const src = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const body = Object.entries(src.spans).map(([s, { skills, cells }]) => `        '${s}': {\n            skills: ${JSON.stringify(skills)},\n`
    + `            cells: ${JSON.stringify(cells.map((c) => [c.n, c.deathless, c.L, c.F]))},\n        },`).join('\n');
const text = `/**
 * GENERATED by scripts/test/extract-noiz2sa-measured-spans.mjs from scripts/data/noiz2sa-measured-spans.json — do not
 * edit by hand.
 *
 * Spans measured as a whole (the page's visit, restart on a hit, hundreds to thousands of attempts a cell), each at
 * its own measured skills (0 and 100 among them), per cell [n, deathless, L, F] as in \`noiz2saDifficultyData.js\`.
 * The difficulty model reads each like a measured triple, on its own skills, instead of the product of its scenes.
 * See CC/docs/cloud-reports/noiz2sa-difficulty-optimism.md.
 */
export const NOIZ2SA_MEASURED_SPANS = Object.freeze({
    cell: ['n', 'deathless', 'L', 'F'],
    spans: {
${body}
    },
});
`;
if (args.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (now !== text) { console.log(`FAIL: ${path.relative(repoRoot, OUT)} differs from ${path.relative(repoRoot, SRC)}`); process.exit(1); }
    console.log(`PASS: ${path.relative(repoRoot, OUT)} matches ${path.relative(repoRoot, SRC)}`);
} else {
    fs.writeFileSync(OUT, text);
    console.log(`wrote ${path.relative(repoRoot, OUT)}`);
}
