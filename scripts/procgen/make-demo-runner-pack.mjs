#!/usr/bin/env node
/**
 * Generate the committed demo RUNNER region-library pack + register it in the
 * region-libraries index (region-library F6c). The runner analogue of
 * make-demo-bounce-pack.mjs: runner is a zone/portal substrate exactly like bounce,
 * so each entry carries its emitted rules verbatim + the runner level payload.
 * Captured items are ignored at placement (the sphere driver reassigns each node's
 * items onto the slots), so capturing a grant/victory zone is fine.
 *
 * Each entry is a runner region built DIRECTLY via generateZoneForSpecs (the
 * requirement-targeted sphere hook — one generate-and-verify per level, a couple of
 * seconds each), NOT via the default 6-zone table (extractZoneRules), whose lazy
 * build costs a minute-plus of solver time. Both paths yield a valid runner region;
 * the spec path is fast and lets us pin the exit sides + a single ungated location
 * slot per entry. Captured with all four re-keyable exit sides so the sphere driver
 * can relabel any needed side.
 *
 * Deterministic + idempotent (content-hash identity). Re-run after any capture
 * change; the e2e (verify-region-library-sphere-roundtrip-runner.mjs) loads the
 * output.
 *   node scripts/procgen/make-demo-runner-pack.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '../..');
const OUT = path.join(repoRoot, 'frontend/region-libraries/demo-runner-pack.json');
const INDEX = path.join(repoRoot, 'frontend/region-libraries/region_library_files.json');

const imp = (p) => import(pathToFileURL(path.join(repoRoot, p)));
const { generateZoneForSpecs } = await imp('frontend/modules/runnerDemo/runnerDemoLibrary.js'); // registers runner
const { substrateRegistry } = await imp('frontend/modules/shared/procgen/substrateRegistry.js');
const { assembleZoneRegion } = await imp('frontend/modules/procgenPipeline/procgenPipelineEngine.js');
const { stampLibraryIdentity, validateRegionLibrary } = await imp('frontend/modules/procgenPipeline/regionLibraryValidator.js');

const runner = substrateRegistry.get('runner');
const SIDES = ['N', 'E', 'S', 'W'];

// Capture a runner entry with all four re-keyable portals (ungated) + one ungated
// pickup slot — so the sphere driver can relabel any needed side and place its one
// item per region. `seed` keeps generation deterministic across re-runs.
function capture(seed, item, id, name) {
    const zoneRules = generateZoneForSpecs({
        region_id: 'orig',
        exitSpecs: SIDES.map((s) => ({ side: s, requirement: [] })),
        locationSpecs: [{ id: 'loc0', item, requirement: [] }],
        seed,
    });
    const region = assembleZoneRegion({
        substrate: 'runner', region_id: 'orig', regionSize: { width: 8, height: 6 },
        exitSides: SIDES, zoneRules, zonePayload: {},
    });
    return runner.captureLibraryEntry(region, { entry_id: id, name });
}

const library = {
    schema_version: 1,
    library_id: 'demo-runner-pack',
    name: 'Demo Runner Pack',
    description: 'Two committed runner zone rooms (all four re-keyable exit sides, '
        + '1 location slot each) for exercising sphere-growth library reuse (F6c). '
        + 'Generated by scripts/procgen/make-demo-runner-pack.mjs.',
    provenance: { generator: 'region-library demo (F6c)' },
    entries: [
        capture(7, 'Springs', 'rn_room_a', 'Runner Room A'),
        capture(11, 'Glide', 'rn_room_b', 'Runner Room B'),
    ],
};
stampLibraryIdentity(library);

const vr = validateRegionLibrary(library, {
    entryCapabilityCheck: (e) => runner.validateLibraryEntry(e),
});
if (!vr.ok) {
    console.error('FAIL: generated pack does not validate:', vr.errors.join('; '));
    process.exit(1);
}

fs.writeFileSync(OUT, `${JSON.stringify(library, null, 2)}\n`);

// Register (or update) the index entry.
const index = JSON.parse(fs.readFileSync(INDEX, 'utf8'));
index.libraries = (index.libraries ?? []).filter((l) => l.file !== 'demo-runner-pack.json');
index.libraries.push({
    file: 'demo-runner-pack.json',
    library_id: library.library_id,
    name: library.name,
    description: 'Two runner zone rooms (four re-keyable sides, 1 slot each).',
    entry_count: library.entries.length,
    substrates: ['runner'],
});
fs.writeFileSync(INDEX, `${JSON.stringify(index, null, 2)}\n`);

console.log(`wrote ${path.relative(repoRoot, OUT)} (library_id=${library.library_id}, `
    + `${library.entries.length} entries) + updated index`);
