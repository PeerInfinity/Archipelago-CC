#!/usr/bin/env node
/**
 * generate-tape-index — the committed tape roster, as a file a static host
 * can serve.
 *
 * ── WHY THIS EXISTS ──────────────────────────────────────────────────
 *
 * `watch.html`'s tape picker used to learn what tapes exist by fetching the
 * DIRECTORY and regexing `href="…json"` out of the server's listing. That
 * works on `python -m http.server` and nowhere else: GitHub Pages emits no
 * listing, so on the published site the picker read `— no directory
 * listing —`, the SOLVE arm's presets dropdown read `— no preset list —`,
 * and the only way into a tape was to already know its name and type it
 * into `?tape=`. The 153 tapes were tracked, deployed and reachable the
 * whole time; nothing could enumerate them.
 * ⚖ The user, 2026-08-19: *"keep the tapes in the repository, and fix the
 * page to use them"*.
 *
 * ⛓ `loadTapeIndex`'s own docblock ARGUED AGAINST a manifest, and the
 * argument was a good one: *"slice 4 records segment tapes as it goes, and
 * a manifest would be stale between the recording and the regeneration that
 * noticed"*. A file listing a directory is a second copy of that directory,
 * and second copies drift. That argument is answered by a MECHANISM rather
 * than by a promise:
 *
 *   1. this generator is the only thing that writes the file, and it is
 *      deterministic — sorted, no timestamp, no run-dependent field — so
 *      `--check` is a regenerate-no-diff gate;
 *   2. ⛔ and regenerate-no-diff is NOT ENOUGH ON ITS OWN (trap 397): it
 *      cannot see a manifest that stopped COVERING its directory, because
 *      a stale generator regenerates its own stale answer perfectly. So
 *      `tapeIndexManifest.test.js` asserts, against the DIRECTORY and the
 *      TAPES, that the row set is `readdirSync(tapes)` minus this file and
 *      that every row's fields equal the tape on disk. Two gates, two
 *      different questions.
 *
 * And the page keeps the fallback: no manifest ⇒ the directory listing, as
 * before, so a roster kept somewhere other than `fixtures/tapes/` still
 * lists its siblings without one. The picker SAYS which of the two it used.
 *
 * ⚠ THE FILE LIVES IN THE DIRECTORY IT INDEXES, which is a directory other
 * code ENUMERATES. `fixtures/index.js`'s `fixtureNames()` is
 * `readdirSync(TAPES_DIR).filter(endsWith('.json'))` — so without an
 * exclusion this manifest becomes a fixture named `index`, with no
 * expectation and no tape shape, and the differential and every tape suite
 * red on it. The exclusion is one named constant, `TAPE_INDEX_FILE`,
 * exported from `fixtures/index.js` and used here, in that filter, and in
 * the browser's listing regex.
 *
 * Run:
 *   node scripts/procgen/generate-tape-index.mjs            # write it
 *   node scripts/procgen/generate-tape-index.mjs --check    # gate it
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, '..', '..');
const { TAPES_DIR, TAPE_INDEX_FILE } = await import(
    join(REPO, 'frontend/modules/seedlingDemo/fixtures/index.js'));

const DIR_REL = 'frontend/modules/seedlingDemo/fixtures/tapes';
const OUT = join(TAPES_DIR, TAPE_INDEX_FILE);
const CHECK = process.argv.includes('--check');

/**
 * One row per tape, carrying EXACTLY the fields `populatePicker`'s
 * `summarise` reads — so the picker can label 153 options without fetching
 * 153 tapes — and nothing else. A manifest that grew a field nobody reads
 * would be a second copy of the tape, which is the drift this design is
 * trying not to buy.
 *
 * ⚠ `noHazards` is ABSENT from 11 of the 153 tapes, and absent is not `[]`
 * to a reader that might later care. It is emitted only when the tape has
 * it, and the test compares presence as well as value.
 */
function rowFor(file) {
    const t = JSON.parse(readFileSync(join(TAPES_DIR, file), 'utf8'));
    const row = {
        file,
        tickCount: t.tick_count ?? null,
        bootLevel: t.boot?.level ?? null,
        tapeVersion: t.tape_version ?? null,
    };
    if (t.noHazards !== undefined) row.noHazards = t.noHazards;
    return row;
}

const files = readdirSync(TAPES_DIR)
    .filter((f) => f.endsWith('.json') && f !== TAPE_INDEX_FILE)
    .sort();

const manifest = {
    $comment: 'GENERATED by scripts/procgen/generate-tape-index.mjs — do not hand-edit. '
        + 'The tape picker in watch.html reads this so it can enumerate the roster on a '
        + 'static host with no directory listing (GitHub Pages). Regenerate with that '
        + 'script; `--check` gates it, and tapeIndexManifest.test.js gates it against the '
        + 'directory itself.',
    dir: DIR_REL,
    tapes: files.map(rowFor),
};
const text = `${JSON.stringify(manifest, null, 2)}\n`;

if (!CHECK) {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT} — ${manifest.tapes.length} tapes`);
    process.exit(0);
}

let current = null;
try { current = readFileSync(OUT, 'utf8'); } catch { /* absent, reported below */ }
if (current === text) {
    console.log(`OK: ${TAPE_INDEX_FILE} is up to date — ${manifest.tapes.length} tapes`);
    process.exit(0);
}
if (current === null) {
    console.log(`FAIL: ${OUT} does not exist. Run without --check to write it.`);
    process.exit(1);
}
// Name the difference rather than print two blobs: the reader wants to know
// WHICH tapes moved, which is what a regenerated roster disagrees about.
const was = JSON.parse(current);
const had = new Set((was.tapes ?? []).map((r) => r.file));
const has = new Set(manifest.tapes.map((r) => r.file));
const added = [...has].filter((f) => !had.has(f));
const gone = [...had].filter((f) => !has.has(f));
const moved = manifest.tapes.filter((r) => {
    const old = (was.tapes ?? []).find((o) => o.file === r.file);
    return old && JSON.stringify(old) !== JSON.stringify(r);
}).map((r) => r.file);
console.log(`FAIL: ${TAPE_INDEX_FILE} is STALE — regenerate it`);
if (added.length) console.log(`  on disk, missing from the manifest: ${added.join(', ')}`);
if (gone.length) console.log(`  in the manifest, missing from disk: ${gone.join(', ')}`);
if (moved.length) console.log(`  fields disagree with the tape: ${moved.join(', ')}`);
if (!added.length && !gone.length && !moved.length) {
    console.log('  the rows agree; the difference is in the envelope ($comment/dir/format)');
}
process.exit(1);
