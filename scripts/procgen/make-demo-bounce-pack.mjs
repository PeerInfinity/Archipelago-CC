#!/usr/bin/env node
/**
 * Generate the committed demo BOUNCE region-library pack + register it in the
 * region-libraries index (region-library F6a). Mirrors the demo-maze-pack (F3)
 * but for the CONTENT (zone) capture contract: each entry carries its emitted
 * rules verbatim + the bounce level payload. Captured items are ignored at
 * placement (the sphere driver reassigns each node's items onto the slots), so
 * capturing the victory zone is fine.
 *
 * Deterministic + idempotent (content-hash identity). Re-run after any capture
 * change; the e2e (verify-region-library-sphere-roundtrip.mjs) loads the output.
 *   node scripts/procgen/make-demo-bounce-pack.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '../..');
const OUT = path.join(repoRoot, 'frontend/region-libraries/demo-bounce-pack.json');
const INDEX = path.join(repoRoot, 'frontend/region-libraries/region_library_files.json');

const imp = (p) => import(pathToFileURL(path.join(repoRoot, p)));
await imp('frontend/modules/mazeRoom/mazeRoomLibrary.js'); // registers maze + bounce
const { extractZoneRules } = await imp('frontend/modules/bounceDemo/bounceDemoLibrary.js');
const { substrateRegistry } = await imp('frontend/modules/shared/procgen/substrateRegistry.js');
const { assembleZoneRegion } = await imp('frontend/modules/procgenPipeline/procgenPipelineEngine.js');
const { stampLibraryIdentity, validateRegionLibrary } = await imp('frontend/modules/procgenPipeline/regionLibraryValidator.js');

const bounce = substrateRegistry.get('bounce');
const SIDES = ['N', 'E', 'S', 'W'];

// Capture a bounce entry for zone `zoneIdx` with all four re-keyable portals +
// its pickup slots — so the sphere driver can relabel any needed side and place
// up to 2 items (maxItemsPerRegion) per region.
function capture(zoneIdx, id, name) {
    const zoneRules = extractZoneRules(zoneIdx, { region_id: 'orig', exitSides: SIDES });
    const region = assembleZoneRegion({
        substrate: 'bounce', region_id: 'orig', regionSize: { width: 8, height: 6 },
        exitSides: SIDES, zoneRules, zonePayload: {},
    });
    return bounce.captureLibraryEntry(region, { entry_id: id, name });
}

const library = {
    schema_version: 1,
    library_id: 'demo-bounce-pack',
    name: 'Demo Bounce Pack',
    description: 'Two committed bounce zone rooms (all four re-keyable exit sides, '
        + '2 location slots each) for exercising sphere-growth library reuse (F6a). '
        + 'Generated by scripts/procgen/make-demo-bounce-pack.mjs.',
    provenance: { generator: 'region-library demo (F6a)' },
    entries: [
        capture(1, 'bn_tower', 'Easy Tower'),
        capture(4, 'bn_fork', 'Fork'),
    ],
};
stampLibraryIdentity(library);

const vr = validateRegionLibrary(library, {
    entryCapabilityCheck: (e) => bounce.validateLibraryEntry(e),
});
if (!vr.ok) {
    console.error('FAIL: generated pack does not validate:', vr.errors.join('; '));
    process.exit(1);
}

fs.writeFileSync(OUT, `${JSON.stringify(library, null, 2)}\n`);

// Register (or update) the index entry.
const index = JSON.parse(fs.readFileSync(INDEX, 'utf8'));
index.libraries = (index.libraries ?? []).filter((l) => l.file !== 'demo-bounce-pack.json');
index.libraries.push({
    file: 'demo-bounce-pack.json',
    library_id: library.library_id,
    name: library.name,
    description: 'Two 8x6 bounce zone rooms (four re-keyable sides, 2 slots each).',
    entry_count: library.entries.length,
    substrates: ['bounce'],
});
fs.writeFileSync(INDEX, `${JSON.stringify(index, null, 2)}\n`);

console.log(`wrote ${path.relative(repoRoot, OUT)} (library_id=${library.library_id}, `
    + `${library.entries.length} entries) + updated index`);
