/**
 * procgenHelpBaseline — **THE DOCUMENT `check-procgen-help.mjs --write-baseline`
 * WRITES, AND ONLY THE FIELDS THAT DO NOT MOVE RUN TO RUN** (slice
 * seedling-headless-G1, 2026-09-15).
 *
 * ⛔ WHAT WAS IN IT, MEASURED. Two consecutive `--write-baseline` runs at
 * `cf0cd3fdb9` agreed on MEMBERSHIP (250 = 250) and disagreed on 247 entries:
 * `ms` 246 (the child's wall), `why` 110 (the throwaway tree's random
 * `/tmp/procgen-help-tree-XXXXXX` name inside quoted stderr; "ran past the
 * 5000 ms ceiling and was killed" on one run and not the other; the printed
 * line count of a door killed at its ceiling), and `wrote` 1 (a writer killed
 * at its 5 s ceiling had written 11 files on one run and 12 on the next).
 * `inheritedOutput` and `helpResidue`: 0.
 *
 * ⛓ WHAT THE GATE READS BACK: the entry NAMES (the import-door membership) and
 * `inheritedOutput` (the per-file control a bounded face attributes help-door
 * output with). Nothing reads `why`, `ms` or `wrote`: every failure message the
 * gate prints is built from the CURRENT run's evidence. So:
 *   · `ms` is DROPPED — a timing belongs in the run's log, where it is printed.
 *   · `why` is DROPPED — it was prose about one run; the same prose for today's
 *     tree is `check-procgen-help.mjs --only=<file> --json`.
 *   · `wrote` is DROPPED too, and its count with it. The first cut of this
 *     slice kept the DIRECTORIES (`wroteUnder`) on the theory that only the
 *     file count was truncated; two writes at `117712c827` measured it moving
 *     on 2 entries anyway — a writer killed at its ceiling wrote nothing on
 *     one run, and a `__pycache__/` appeared on one run only. What a door
 *     writes today is in `--only=<file> --json`.
 *   · `helpResidue` is the KIND of each help-door failure, never its text
 *     (`residueKinds`): the reasons `check-procgen-help.mjs` composes quote
 *     the throwaway tree's random name, stderr excerpts, line and file
 *     counts — the same load-dependent prose `why` was dropped for. 0 of 250
 *     entries carry one today; the row in the test file constructs one so the
 *     field cannot start moving the day an instrument's `--help` breaks.
 * ⛔ A new field here must be run-invariant; the row in the test file says so
 * by constructing two runs that differ only in load.
 */
const NOTE = 'GENERATED by `node scripts/procgen/check-procgen-help.mjs --write-baseline` '
    + '(R9 slice P4a, ⚖ 47b (4)). The instruments whose MODULE SCOPE does work when '
    + 'the file is merely imported — no argv, no main guard. ⛔ An entry here is NOT '
    + 'an approved side effect, it is a KNOWN one: closing this door means moving a '
    + "file's work into a `main()`, which for a producer can move its standing "
    + 'stdout md5 (⚖ ruling 8). The list reds BOTH ways — a new entrant, and an '
    + 'entry that has been fixed. The `--help` door has no list and no exceptions. '
    + 'Only run-invariant fields are recorded (G1): why a door fails today is '
    + '`--only=<file> --json`.';

/**
 * ⛓ WHAT EACH FILE'S HELP DOOR INHERITED FROM ITS IMPORTS — the INTERSECTION
 * of that file's two doors. ⛔ Stack frames are excluded: a frame differs
 * between launch methods for the same warning.
 */
const lines = (t) => new Set((t ?? '').split('\n').map((l) => l.trim())
    .filter((l) => l && !/^at\s/.test(l)));
export const inheritedOf = (r) => {
    const imp = new Set([...lines(r.import.stdout), ...lines(r.import.stderr)]);
    return [...new Set([...lines(r.help.stdout), ...lines(r.help.stderr)])]
        .filter((l) => imp.has(l)).sort();
};

/**
 * ⛓ THE KIND of a help-door reason, off the FIXED PREFIX each producer in
 * `check-procgen-help.mjs` writes (`localWhy` and the disk observers) — the
 * run-specific tail (tree name, excerpt, counts) is what this discards.
 * Sorted and deduplicated, so order of discovery moves nothing either.
 */
const RESIDUE_KINDS = [
    /** ⛓ a ceiling kill IS a non-zero exit: under load the same door is killed
     *  where unloaded it exits — one kind, or the field moves with the box. */
    [/^ran past /, 'exit'],
    [/^exit /, 'exit'],
    [/^left .* cache/, 'cache'],
    [/^printed to stderr/, 'stderr'],
    [/^printed .* stdout/, 'stdout'],
    /** ⛓ what a killed door WROTE is load-dependent (measured: 11 files, 12,
     *  nothing) and so is the porcelain move it causes — neither is a kind. */
    [/^wrote /, null],
    [/porcelain|MOVED|RESTORED/, null],
];
export const residueKinds = (why) => [...new Set((why ?? []).map((w) =>
    (RESIDUE_KINDS.find(([re]) => re.test(w)) ?? [null, 'other'])[1]).filter(Boolean))].sort();

/** The baseline file's text for `rows` (the gate's judged rows) measured at `head`. */
export function baselineDocument(rows, head) {
    const effectful = Object.fromEntries(rows.filter((r) => !r.import.ok)
        .sort((a, b) => a.file.localeCompare(b.file))
        .map((r) => [r.file, {
            inheritedOutput: inheritedOf(r),
            helpResidue: r.help.ok ? null : residueKinds(r.help.why),
        }]));
    return `${JSON.stringify({
        note: NOTE,
        measuredAt: head,
        counts: {
            instruments: rows.length,
            importDoorEffectful: Object.keys(effectful).length,
        },
        importDoorEffectful: effectful,
    }, null, 2)}\n`;
}
