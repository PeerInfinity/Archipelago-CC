const sha = (v) => createHash('sha256').update(JSON.stringify(v)).digest('hex').slice(0, 16);
const say = (line = '') => process.stdout.write(`${line}\n`);
const note = (line) => process.stderr.write(`${line}\n`);

/**
 * ⚖ §1.14's ruling, applied one instrument over: **a measurement harness may
 * CATCH AND CLASSIFY throws.** The oracle's own catch stays narrow (traps
 * 171/173) and is untouched; what this does is stop one aborting seed from
 * ending a batch whose whole job is to report what aborted.
 */
function attempt(fn) {
    try {
        return { ok: true, value: fn() };
    } catch (e) {
        return { ok: false, error: { name: e.name, message: e.message, cause: e.cause?.name ?? null } };
    }
}

// ── the pool scan ─────────────────────────────────────────────────────

/**
 * Generate one candidate and decide whether it JOINS the batch.
 *
 * Three rejections, each named: the run ABORTED (an engine throw the oracle
 * does not classify — §15.5's `PhysicsV2Error` class, measured at 6/72 on
 * this roster), the loop SATURATED short of the target, or the final level
 * failed certification. ⛔ Every one is reported; none is silently retried.
 */
function candidate(seed, biome) {
    const palette = GENERATE_BIOMES[biome];
    const built = attempt(() => generateStep({ seed, biome, step: BOUNDS.obstacleTarget,
        bounds: BOUNDS, budget: BUDGET }));
    if (!built.ok) {
        return { seed, biome, accepted: false, why: 'ABORTED', detail: built.error };
    }
    const state = built.value;
    if (state.summary.keptCount < BOUNDS.obstacleTarget) {
        return {
            seed,
            biome,
            accepted: false,
            why: 'SATURATED',
            detail: {
                stop: state.summary.stop,
                kept: state.summary.keptCount,
                target: BOUNDS.obstacleTarget,
                message: `${BOUNDS.saturationK} consecutive step(s) kept nothing`,
            },
        };
    }
    const solved = attempt(() => solve(state.record,
        bootStaging({
            boot: state.model.boot(),
            items: palette.items ?? null,
            pins: state.summary.pins,
        }),
        state.model.goals, BUDGET, { name: `batch-s${seed}-${biome}` }));
    if (!solved.ok) {
        return { seed, biome, accepted: false, why: 'FINAL SOLVE THREW', detail: solved.error };
    }
    const out = solved.value;
    if (out.verdict !== 'SOLVED' || !out.certification?.certified) {
        return {
            seed,
            biome,
            accepted: false,
            why: 'NOT CERTIFIED',
            detail: { verdict: out.verdict, reasonText: out.reasonText ?? null },
        };
    }
    return { seed, biome, accepted: true, state, out };
}

// ── certification, to §12.1's discharge-existence standard ────────────

function certify(state, out) {
    const strategies = (out.records ?? []).map((r) => r.strategy);
    const clearers = state.summary.kept
        .filter((k) => verbOf(k.family))
        .map((k) => ({ template: k.template, family: k.family, strategy: verbOf(k.family) }));
    // ⛓ SLICE 5: the ONE discharge test. It answers `null` for a family with no
    // verb, which cannot reach here — `clearers` is already filtered to the
    // families that HAVE one, and that filter is now the same function.
    const discharged = clearers.filter((c) => dischargesVerb(c.family, out.records));
    return {
        collectCertified: out.certification.certified,
        collected: out.certification.collected ?? [],
        strategies,
        clearersKept: clearers,
        clearersDischarged: discharged,
        /**
         * ⚠ NOT EVERY KEPT CLEARER IS ON THE ROUTE, and that is not a defect —
         * §12.1 measured exactly this ("a NEAR door can be squarely on the
         * route and a FAR one need never be walked into"). What the standard
         * forbids is calling a clearer PROVEN on a keep-count; so the report
         * says how many of the kept clearers the final walk actually
         * discharged, and names them.
         */
        dischargedCount: discharged.length,
        scratchClears: out.scratchClears ?? [],
        ticks: out.ticks,
    };
}

