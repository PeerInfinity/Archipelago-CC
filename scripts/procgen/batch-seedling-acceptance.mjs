say(`bounds: obstacleTarget=${BOUNDS.obstacleTarget} triesPerStep=${BOUNDS.triesPerStep} `
    + `saturationK=${BOUNDS.saturationK}`);
say(`budget: maxTicksPerTarget=${BUDGET.maxTicksPerTarget} (⛓ TICKS — no budget here is `
    + 'denominated in milliseconds, so this batch reproduces on a loaded box)');
say(`⚖ THE SAME BUDGET OBJECT RUNS BOTH ARMS OF EVERY DIFFERENTIAL. No budget is `
    + 'escalated anywhere in this script (⚖ §1.10a).');
say('');

for (const [biome, b] of Object.entries(report.biomes)) {
    say(`## ${biome} — ${b.accepted.length} level(s)`);
    say('');
    for (const p of b.phases) {
        say(`scan phase: take ${p.take} from ${p.name} — order `
            + `[${p.scanOrder.join(', ')}${p.scanOrder.length >= 15 ? ', …' : ''}]`);
    }
    say('');
    say('| seed | carrier? | kept (family x n) | attempts | skeleton→final ticks | certified | '
        + 'clearers discharged | 2-process | requirements |');
    say('|---|---|---|---|---|---|---|---|---|');
    for (const a of b.accepted) {
        const fams = {};
        for (const k of a.kept) fams[k.family] = (fams[k.family] ?? 0) + 1;
        say(`| ${a.seed} | ${a.carrier ? 'YES (kill)' : 'no'} `
            + `| ${Object.entries(fams).map(([f, n]) => `${f}x${n}`).join(' ')} `
            + `| ${a.attempts} | ${a.skeletonTicks}→${a.finalTicks} `
            + `| ${a.cert.collectCertified ? 'YES' : 'NO'} `
            + `| ${a.cert.dischargedCount}/${a.cert.clearersKept.length}`
            + `${a.cert.clearersDischarged.length
                ? ` (${a.cert.clearersDischarged.map((c) => c.strategy).join(',')})` : ''} `
            + `| ${a.det.identical && a.det.cliMatches ? `identical ${a.det.md5}` : '⛔ DRIFT'} `
            + `| ${a.req.verdict} |`);
    }
    say('');

    /**
     * ⚖ THE SKIPPED-SEED REPORT (§15.8's OBLIGATION). Every seed the scan
     * touched, in order, with the reason it was not chosen.
     */
    const skipped = b.touched.filter((t) => !t.accepted);
    say(`### seeds SKIPPED — ${skipped.length} of ${b.touched.length} touched `
        + `(⚖ §15.8: a batch that quietly picks clean seeds reads as "generation is `
        + 'abort-free" when it is measured not to be)');
    if (!skipped.length) {
        say('');
        say(`(none — the first ${b.touched.length} seed(s) of the scan order all `
            + 'produced a certified level. That is a fact about this scan, not about the '
            + 'generator: the census below is the denominator, and it is re-measured on '
            + 'every run rather than cited.)');
    } else {
        say('');
        say('| seed | scan phase | why | detail |');
        say('|---|---|---|---|');
        for (const s of skipped) {
            const d = s.detail ?? {};
            say(`| ${s.seed} | ${s.phase} | ${s.why} | ${d.name ? `${d.name}: ` : ''}`
                + `${(d.message ?? d.reasonText ?? JSON.stringify(d)).slice(0, 200)
                    .replace(/\|/g, '\\|').replace(/\n/g, ' ')} |`);
        }
    }
    say('');

    if (biome === 'post-sword') {
        const carriers = b.accepted.filter((a) => a.carrier);
        say(`⚖ THE CARRIER OBLIGATION: the batch owes at least THREE sword-gated `
            + `carriers among its post-sword five. It has **${carriers.length}** `
            + `(seeds ${carriers.map((a) => a.seed).join(', ') || 'none'}) and `
            + `${b.accepted.length - carriers.length} control level(s) `
            + `(seeds ${b.accepted.filter((a) => !a.carrier).map((a) => a.seed).join(', ')
                || 'none'}) whose differential should come back "rule not established".`);
        say('');
    }
    say('### requirements reports, per level');
    say('');
    for (const a of b.accepted) {
        say(`**seed ${a.seed}** — ${a.req.verdict}`);
        if (a.req.why) say(`  · ${a.req.why}`);
        for (const r of a.req.rows) {
            say(`  · ${r.item} (\`${r.flag}\`): WITH ${r.withVerdict}`
                + `${r.withTicks ? ` (${r.withTicks}t)` : ''} / WITHOUT ${r.withoutVerdict}`
                + `${r.withoutTicks ? ` (${r.withoutTicks}t)` : ''} ⇒ **${r.verdict}**`
                + `${r.verdict === 'REQUIRED' ? `  [evidence: ${r.evidence}]` : ''}`
                + `${r.inert ? '  [and INERT — the identical tick count says the item '
                    + 'changed nothing about the walk, which is more than "not required"]'
                    : ''}`);
            say(`      ${r.label}`);
            if (r.howToReadTheText) say(`      ⚠ ${r.howToReadTheText}`);
            if (r.withoutReason) {
                say(`      without-arm's own text: ${r.withoutReason.slice(0, 260)}`);
            }
        }
        say('');
    }
}

if (CENSUS > 0) {
    say(`## ⚖ THE ABORT CENSUS — seeds 1..${CENSUS} of BOTH biomes, at these bounds`);
    say('');
    say('⛔ The skipped tables above name what THIS SCAN dropped, which is the obligation. '
        + 'This is the denominator behind it: a scan that takes the first five clean seeds '
        + 'reports zero skips whatever the underlying rate is. ⛓ THE HISTORICAL NUMBERS ARE '
        + 'CITED AS HISTORY: §15.5 measured 6 of 72 runs aborting on the ELEVEN-ROW roster '
        + 'and 1 of 72 on the committed nine — both of which were pre-parameterization '
        + 'rosters that no longer exist (the GENERATE-mode UI arc\'s slice 2 collapsed them '
        + 'to 7 parameterized bases). The table below is this run\'s own measurement, and it '
        + 'is the only one that describes the roster in the tree.');
    say('');
    say('| biome | seeds | ABORTED | saturated short of target | clean |');
    say('|---|---|---|---|---|');
    const censusRows = [];
    for (const biome of Object.keys(GENERATE_BIOMES)) {
        let aborted = 0;
        let saturated = 0;
        const aborts = [];
        for (let seed = 1; seed <= CENSUS; seed += 1) {
            note(`[stderr] census ${biome} seed ${seed}…`);
            const built = attempt(() => generateStep({ seed, biome,
                step: BOUNDS.obstacleTarget, bounds: BOUNDS, budget: BUDGET }));
            if (!built.ok) {
                aborted += 1;
                aborts.push({ seed, name: built.error.cause ?? built.error.name });
            } else if (built.value.summary.keptCount < BOUNDS.obstacleTarget) saturated += 1;
        }
        say(`| ${biome} | 1..${CENSUS} | **${aborted}** | ${saturated} | `
            + `${CENSUS - aborted - saturated} |`);
        censusRows.push({ biome, aborts });
    }
    say('');
    for (const r of censusRows) {
        say(`  · ${r.biome} aborts: ${r.aborts.length
            ? r.aborts.map((a) => `seed ${a.seed} (${a.name})`).join(', ')
            : '(none in this range)'}`);
    }
    say('');
}

say('## the empty-room and saturation cases (⚖ §7.5)');
say('');
say('EMPTY ROOM: every level\'s trace row 0 IS the skeleton solve — the bordered room and '
    + 'its goal, before any template. `generateLevel` refuses to start when it does not '
    + 'solve, so a row 0 with a tick count is the empty-room case exercised, per level.');
for (const [biome, b] of Object.entries(report.biomes)) {
    for (const a of b.accepted) {
        say(`  · ${biome} seed ${a.seed}: skeleton solved in ${a.skeletonTicks} ticks`);
    }
}
say('');
const saturated = Object.values(report.biomes)
    .flatMap((b) => b.touched.filter((t) => t.why === 'SATURATED'));
