/**
 * batch-seedling-acceptance — THE ARC'S EXIT-CRITERIA BATCH AND THE
 * PER-LEVEL REQUIREMENTS REPORT.
 *
 * Seedling PROCGEN PoC arc, slice 5 (kickoff §7, made concrete; ⚖ ruling
 * §1.10a). Generates 5 pre-sword + 5 post-sword levels from RECORDED seeds,
 * certifies each, proves each regenerates byte-identically in a SECOND
 * PROCESS, and ships each one's REQUIREMENTS REPORT.
 *
 * ── ⚖⚖ THE REQUIREMENTS REPORT'S LAW, VERBATIM (ruling §1.10a) ────────
 *
 * *"for each certified level, re-solve with items removed; 'solves with X /
 * refuses without X at the SAME per-solve budget' ⇒ X recorded as required.
 * ⛔⛔ THE CLAIM IS SOLVER-RELATIVE AND BOUNDED BY CONSTRUCTION (user's own
 * warning, from the bounce/runner substrates: impossibility-proving via
 * exhaustive search was the failure mode there — NEVER escalate budgets to
 * chase certainty; a refusal at standard budget is the datum, 'rule not
 * established' is a named verdict, and no exhaustive search exists anywhere
 * in this design)."*
 *
 * So, in this file, concretely:
 *
 *  1. **ONE BUDGET OBJECT, BOTH ARMS.** `BUDGET` is frozen and passed to the
 *     with-arm and the without-arm unchanged. ⛔ There is no code path here
 *     that raises it, retries, or widens anything on a refusal — the refusal
 *     at the standard budget IS the datum.
 *  2. **EVERY "required" VERDICT CARRIES ITS SOLVER-RELATIVE LABEL**, in the
 *     row, not in a footnote. The claim is about THIS SOLVER at THIS BUDGET
 *     and never about the level in the abstract.
 *  3. **"rule not established" IS A FIRST-CLASS VERDICT**, printed as an
 *     answer rather than as an absence. A pre-sword level whose biome
 *     declares no item TRUE has NOTHING to remove, and the report says that
 *     in words rather than printing an empty list.
 *
 * ── ⛔ AND THE THREE FAILURE MODES ARE GRADED, NOT FLATTENED ──────────
 *
 * The batch measured all three on its three carriers — one REFUSED, one
 * BUDGET_EXHAUSTED, one THREW `PhysicsV2Error`. Printing "REQUIRED" three
 * times over three different facts would be a report agreeing with itself,
 * so each REQUIRED row carries an `evidence` grade: STRONG (a solver refusal
 * within budget — ⚖ §1.10a's own datum), BOUND-DEPENDENT (the budget is what
 * ended it; the verdict stands and the bound is visibly load-bearing), or
 * WEAK (an ENGINE throw — §15.9's approach-drive question, which is not a
 * claim about the level at all).
 *
 * ⛓ The CONTROLS get the mirror of it: when both arms solve at the SAME tick
 * count, the row says INERT — the item did not merely fail to be necessary,
 * it changed nothing about the walk. That is §12.2's biome-level inertness
 * arriving per level, and it is a stronger statement than "not required".
 *
 * ── ⚠⚠ THE WITHOUT-ARM'S FAILURE IS BUDGET-SHAPED, AND THAT IS EXPECTED ─
 *
 * §15.8's warning, and it decides how these rows must be read. Without the
 * sword there is no refusal that says "no sword": `weaponForPress`
 * (`levelRun.js:3667`) returns `null` when the inventory slot is absent, so
 * a swordless press is a **SILENT NO-OP** — the solver schedules its strikes,
 * spends its ticks against a body that cannot die, and fails on the budget or
 * on the corridor. ⇒ **the DIFFERENTIAL'S VERDICT is what speaks, never the
 * refusal text.** A reader who expected the text to name the sword is the
 * reader this paragraph exists for.
 *
 * ── ⚖ THE SKIPPED-SEED OBLIGATION (§15.8, orchestrator ruling) ────────
 *
 * *"An aborting seed is VISIBLE and is simply not chosen — so the acceptance
 * batch REPORTS how many seeds it skipped and why. A batch that quietly picks
 * five clean levels out of thirteen carriers reads as 'generation is
 * abort-free' when 6 of 72 runs die."* So every seed this batch TOUCHED is in
 * the report: accepted, or rejected with its class and the engine's own
 * message. The scan order is fixed and printed, so the selection is
 * reproducible rather than curated.
 *
 * ── DETERMINISM IS PROVEN IN TWO PROCESSES, NOT ONE ───────────────────
 *
 * One process proves the generator is a function; two prove it depends on
 * nothing the process carries. Each accepted seed is regenerated by SPAWNING
 * `generate-seedling-level.mjs` twice and comparing the two stdouts to each
 * other AND to this run's own payload. ⛔ stdout only — the CLI writes its
 * timings to stderr, and §15.7's own false alarm was a gate that captured
 * `2>&1`.
 *
 * ⛔ NOTHING IS WRITTEN TO `fixtures/`, EVER (standing law). `--out-dir=`
 * writes payloads where it is told and refuses a path under `fixtures/`.
 *
 * Run:
 *   node scripts/procgen/batch-seedling-acceptance.mjs --out-dir=/tmp/batch
 *   node scripts/procgen/batch-seedling-acceptance.mjs --json
 */

