// ── determinism, in two SEPARATE processes ───────────────────────────

function twoProcessIdentity(seed, biome) {
    const run = () => execFileSync('node', [
        join(HERE, 'generate-seedling-level.mjs'),
        `--seed=${seed}`, `--biome=${biome}`, `--count=${BOUNDS.obstacleTarget}`,
        `--tries=${BOUNDS.triesPerStep}`, `--k=${BOUNDS.saturationK}`,
        /**
         * ⛔ EVERY BOUND THE IN-PROCESS ARM RUNS UNDER IS PASSED, INCLUDING
         * SLICE 3's. `BOUNDS` is `DEFAULT_BOUNDS`, so today this is `=1` either
         * way — but a bound the subprocess DEFAULTED while the in-process arm
         * raised it would report `⛔ DRIFT`, and a determinism red whose cause
         * is a missing flag is the worst kind of false alarm this batch can
         * raise (see §9.9's self-inflicted one).
         */
        `--anchor-tries=${BOUNDS.anchorTriesPerCandidate}`, '--json',
    ], { cwd: REPO, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
    const a = run();
    const b = run();
    return {
        identical: a === b,
        md5: createHash('md5').update(a).digest('hex'),
        bytes: Buffer.byteLength(a),
        payload: JSON.parse(a),
    };
}

// ── the batch ─────────────────────────────────────────────────────────

if (OUT_DIR && OUT_DIR.includes('fixtures/')) {
    note('batch-seedling-acceptance: REFUSED to write under `fixtures/` — committed '
        + 'fixtures are byte-identical artifacts of recorded runs and no tool in this arc '
        + 'writes them (standing law).');
    process.exit(2);
}
if (OUT_DIR) mkdirSync(OUT_DIR, { recursive: true });

const report = { bounds: BOUNDS, budget: BUDGET, biomes: {} };

for (const biome of Object.keys(GENERATE_BIOMES)) {
    const accepted = [];
    const touched = [];
    for (const phase of PHASES[biome]) {
      let taken = 0;
      for (const seed of phase.seeds) {
        if (taken >= phase.take || accepted.length >= PER_BIOME) break;
        if (accepted.some((a) => a.seed === seed)) continue;
        note(`[stderr] ${biome} seed ${seed} (${phase.name})…`);
        const c = candidate(seed, biome);
        touched.push(c.accepted
            ? { seed, accepted: true, phase: phase.name }
            : { seed, accepted: false, phase: phase.name, why: c.why, detail: c.detail });
        if (!c.accepted) continue;
        taken += 1;

        const cert = certify(c.state, c.out);
        const det = twoProcessIdentity(seed, biome);
        const req = requirementsFor(c.state, c.out, { budget: BUDGET });
        const payload = {
            generator: 'scripts/procgen/batch-seedling-acceptance.mjs',
            seed,
            biome,
            bounds: BOUNDS,
            budget: BUDGET,
            summary: c.state.summary,
            level: c.state.record,
            trace: c.state.trace,
            certification: cert,
            requirements: req,
        };
        /**
         * ⛔ THE BATCH'S OWN LEVEL AND THE CLI'S MUST BE THE SAME BYTES, and
         * it is CHECKED rather than assumed — the batch calls `generateStep`
         * and the CLI calls `generateSeedlingLevel`, and the whole point of
         * the ladder's prefix property is that those agree.
         */
        const cliMatches = JSON.stringify(det.payload.level) === JSON.stringify(c.state.record)
            && JSON.stringify(det.payload.trace) === JSON.stringify(c.state.trace);
        if (OUT_DIR) {
            writeFileSync(join(OUT_DIR, `s${seed}-${biome}.json`),
                `${JSON.stringify(payload, null, 2)}\n`);
        }
        accepted.push({
            seed,
            phase: phase.name,
            carrier: c.state.summary.kept.some((k) => k.family === 'kill'),
            levelSha: sha(c.state.record),
            traceSha: sha(c.state.trace),
            kept: c.state.summary.kept,
            attempts: c.state.summary.attempts,
            skeletonTicks: c.state.summary.skeletonTicks,
            finalTicks: cert.ticks,
            cert,
            det: { identical: det.identical, md5: det.md5, bytes: det.bytes, cliMatches },
            req,
        });
      }
    }
    report.biomes[biome] = {
        accepted,
        touched,
        phases: PHASES[biome].map((p) => ({ name: p.name, take: p.take,
            scanOrder: p.seeds.slice(0, 15) })),
    };
}

// ── the report ────────────────────────────────────────────────────────

if (has('json')) {
    say(JSON.stringify(report, null, 2));
    process.exit(0);
}

say('# Seedling PROCGEN PoC — THE ACCEPTANCE BATCH (kickoff §7) + THE REQUIREMENTS REPORT');
