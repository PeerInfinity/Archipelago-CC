/**
 * dump-dj-traces.mjs — expected-trace generator for the SWFRecomp-CC
 * dj-loader exchange (the reusable version of the ad-hoc script that
 * produced dj-loader-traces/region_4_4_expected.json).
 *
 * Simulates a committed preset region zero-input under the SAME step()
 * the rules were derived with (physics.js, the region's embedded dj
 * constants), and emits per-tick states, landings, and — for swept
 * blue movers — the deterministic platformXAt position table their
 * loader must reproduce (phase = ticks since region entry/respawn,
 * t=0 at the spawn state).
 *
 * Usage:
 *   node scripts/procgen/dump-dj-traces.mjs <rules.json> <region_id> \
 *       [--ticks 400] [--grant "Brown platforms@300"] [--out file.json]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import {
    spawnState, step, platformXAt, resolvePhysicsStamp,
} from '../../frontend/modules/bounceDemo/physics.js';

const args = process.argv.slice(2);
if (args.length < 2) {
    console.error('usage: dump-dj-traces.mjs <rules.json> <region_id> '
        + '[--ticks N] [--grant "Item@tick[,Item@tick]"] [--out file.json]');
    process.exit(2);
}
const [rulesPath, regionId] = args;
const opt = (name, dflt) => {
    const i = args.indexOf(name);
    return i >= 0 ? args[i + 1] : dflt;
};
const TICKS = Number(opt('--ticks', 400));
const grants = (opt('--grant', '') || '').split(',').filter(Boolean)
    .map((s) => { const [item, t] = s.split('@'); return { item, t: Number(t) }; });
const outPath = opt('--out', null);

const rules = JSON.parse(readFileSync(rulesPath, 'utf8'));
const sidecars = rules.preset_sidecars?.['1'] ?? {};
const payload = sidecars[regionId]?.playable_payload;
if (!payload) {
    console.error(`region ${regionId} not in preset_sidecars`);
    process.exit(2);
}
const level = payload.params.bounceLevel;
// resolvePhysicsStamp returns the constants object directly (embedded
// constants merged over DEFAULTS).
const C = resolvePhysicsStamp(payload.params.physics);

// Items -> abilities/platform-existence, mirroring the game page: blue/
// brown platforms exist only while their item is held; arrows gate input
// (irrelevant zero-input). Grants apply from their tick onward.
const held = new Set();
function abilitiesAt(t) {
    for (const g of grants) if (t >= g.t) held.add(g.item);
    return {
        left: held.has('Left arrow'),
        right: held.has('Right arrow'),
        blue: held.has('Blue platforms'),
        brown: held.has('Brown platforms'),
        springs: held.has('Springs'),
        jetpacks: held.has('Jetpacks'),
    };
}

let s = spawnState(level, C);
const ticks = [];
const landings = [];
for (let t = 0; t < TICKS; t++) {
    s = step(s, null, level, abilitiesAt(t), C);
    ticks.push({ t: s.t, x: s.x, y: s.y, vy: s.vy, landedOn: s.landedOn });
    if (s.landedOn) landings.push({ t: s.t, platform: s.landedOn, x: s.x, y: s.y });
    if (s.fallen) { landings.push({ t: s.t, fallen: true }); break; }
}

// Deterministic mover tables: one full sweep cycle per swept blue.
const movers = {};
for (const p of level.platforms) {
    if (p.type === 'blue' && p.sweep) {
        const span = p.sweep.max - p.sweep.min;
        const cycle = Math.max(1, Math.ceil((2 * span) / C.BLUE_SPEED));
        movers[p.id] = {
            sweep: p.sweep,
            formula: 'cycle=2*span; ph=((BLUE_SPEED*(t+phase0)) mod cycle + cycle) mod cycle; '
                + 'x = min + (ph<=span ? ph : cycle-ph); t = ticks since region entry/respawn (t=0 at spawn)',
            cycle_ticks: cycle,
            x_by_tick: Array.from({ length: cycle }, (_, t) => platformXAt(p, t, C)),
        };
    }
}

const out = {
    _about: `Expected per-tick traces for ${regionId} of ${rulesPath} under the `
        + 'region\'s embedded dj physics constants, generated by the SAME step() '
        + 'the rules were derived with (frontend/modules/bounceDemo/physics.js). '
        + 'World coordinates (y down, absolute level space). t=0 is the SPAWN '
        + 'state (bottom-center, at rest); align tick offsets at the FIRST LANDING.',
    registration_note: 'platform.y IS the catch line — place block._y = world_y, no offset.',
    constants: C,
    level_id: level.id,
    spawn: { x: level.size.width / 2, y: level.size.height - C.SPAWN_HEIGHT },
    grants,
    landings,
    movers,
    ticks,
};

const json = JSON.stringify(out, (k, v) =>
    typeof v === 'number' && !Number.isInteger(v) ? Number(v.toPrecision(15)) : v);
if (outPath) {
    writeFileSync(outPath, json);
    console.log(`wrote ${outPath} (${landings.length} landings, `
        + `${Object.keys(movers).length} movers, ${ticks.length} ticks)`);
} else {
    console.log(json);
}
