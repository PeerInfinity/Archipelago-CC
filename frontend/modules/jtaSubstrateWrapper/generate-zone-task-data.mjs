// Generator for zoneTaskData.js — a snapshot of the JtA fork's zone task
// definitions (the AP-facing surface: task id/name/type + perk/item
// assignments), regenerated from the committed submodule build.
//
// WHY a snapshot and not a live import: the fork's build/zones.js touches
// `window` at module load (via its import chain), so the headless-safe
// substrate registry library cannot import it directly, and the browser
// pipeline has the fork build only inside an iframe — not in the pipeline's
// module scope. The zone task IDENTITY (which task, its name, which perk it
// grants) is inherently the Archipelago location/item surface and has to
// live outer-repo-side to build the world. This is NOT the stale v0.5.0
// jta-randomizer copy: it is generated fresh from the current Fork build by
// this script, carries the SAVE_VERSION it came from, and drift is caught by
// re-running the generator (a small, auditable diff). Only task identity is
// copied — the economy math (costs/formulas) stays in the fork per the
// zone-randomization plan's Q1.
//
// Regenerate after any fork zone/task change:
//   node frontend/modules/jtaSubstrateWrapper/generate-zone-task-data.mjs
//
// Sources task identity only. Costs/xp are deliberately omitted — the
// balancer sets those at build/load time; snapshotting them would invite
// exactly the stale-cost drift the plan warns against.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { loadJtaEnv } from "../../../CC/scripts/jta-stats/node-env.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const outPath = path.join(here, "zoneTaskData.js");

const env = await loadJtaEnv();
const { zones } = env;
const perksMod = await import(
  pathToFileURL(
    path.resolve(here, "../journey-to-ascension/build/perks.js")
  )
);
const itemsMod = await import(
  pathToFileURL(
    path.resolve(here, "../journey-to-ascension/build/items.js")
  )
);
const simMod = await import(
  pathToFileURL(
    path.resolve(here, "../journey-to-ascension/build/simulation.js")
  )
);

const PerkType = perksMod.PerkType;
const ItemType = itemsMod.ItemType;
const perkName = (t) =>
  t === PerkType.Count ? null : perksMod.PERKS[t]?.name ?? null;
const itemName = (t) =>
  t === ItemType.Count ? null : itemsMod.ITEMS[t]?.name ?? null;

// TaskType enum → readable string (matches zones.ts order).
const TYPE_NAMES = ["Normal", "Travel", "Mandatory", "Prestige", "Boss"];

const zonesOut = zones.ZONES.map((zone, zi) => ({
  zone: zi,
  name: zone.name,
  tasks: zone.tasks.map((def) => ({
    id: def.id,
    name: def.name,
    type: TYPE_NAMES[def.type] ?? String(def.type),
    perk: perkName(def.perk),
    item: itemName(def.item),
    maxReps: def.max_reps,
    hidden: def.hidden_by_default,
    unlocksTask: def.unlocks_task >= 0 ? def.unlocks_task : null,
  })),
}));

const banner =
  `// GENERATED by generate-zone-task-data.mjs — DO NOT EDIT BY HAND.\n` +
  `// Snapshot of the JtA fork's zone task identity (${simMod.SAVE_VERSION}).\n` +
  `// Regenerate: node frontend/modules/jtaSubstrateWrapper/generate-zone-task-data.mjs\n` +
  `//\n` +
  `// AP-facing surface only (id/name/type/perk/item/maxReps/hidden/unlocksTask).\n` +
  `// Costs/xp intentionally omitted — the balancer owns those. See the\n` +
  `// generator header and the zone-randomization plan (Q1/Q3) for why this\n` +
  `// lives outer-repo-side rather than importing the DOM-coupled fork build.\n`;

const body =
  `export const JTA_FORK_SAVE_VERSION = ${JSON.stringify(simMod.SAVE_VERSION)};\n\n` +
  // PerkType.Count is the enum's terminator (== the perk count). The AP
  // grant-suppression patch sets a task's `perk` to this sentinel so the
  // fork's onFullyFinishTask grants nothing locally — the perk arrives only
  // as an AP item (window.grantPerk). Snapshotted here so the headless-safe
  // pipeline can emit suppression patches without importing the fork build.
  `export const JTA_PERK_COUNT = ${JSON.stringify(PerkType.Count)};\n\n` +
  `export const JTA_ZONE_TASK_DATA = ${JSON.stringify(zonesOut, null, 2)};\n`;

fs.writeFileSync(outPath, banner + "\n" + body);
console.log(
  `wrote ${outPath}: ${zonesOut.length} zones, ` +
    `${zonesOut.reduce((a, z) => a + z.tasks.length, 0)} tasks ` +
    `(${simMod.SAVE_VERSION})`
);
process.exit(0);
