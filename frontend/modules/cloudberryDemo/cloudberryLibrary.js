/**
 * ⛓ PRESET SIDECARS M3 — what a STORED Cloudberry payload keys by an exit's side:
 * the engine's back-portal side (`params.backExitSide`) and the authored portal locks
 * (`gate_rules.portals`, keyed by the page's side name). No portal map: the page's
 * `sidePortals`/`exits` are derived at load (`pageParamsForWorld`), never written.
 */
export const CLOUDBERRY_EXIT_SIDES = Object.freeze({
    keys: Object.freeze(['params.backExitSide', 'gate_rules.portals']),
    relabel(payload, moves) {
        const next = JSON.parse(JSON.stringify(payload));
        const params = next?.params;
        if (params && Object.hasOwn(params, 'backExitSide')) {
            const exits = Array.isArray(next.exits) ? next.exits : [];
            for (const m of moves) {
                if (exits.find((x) => x?.exit_id === m.exitId)?.isBackExit === true) params.backExitSide = m.to;
            }
        }
        const portals = next?.gate_rules?.portals;
        if (portals && typeof portals === 'object') {
            const renamed = new Map(moves.map((m) => [PAGE_SIDE[m.from], PAGE_SIDE[m.to]]));
            next.gate_rules.portals = Object.fromEntries(Object.entries(portals)
                .map(([side, rule]) => [renamed.get(side) ?? side, rule]));
        }
        return next;
    },
});

// ── Region-library hooks ──

const SIDES = Object.freeze(['N', 'E', 'S', 'W']);

/** Re-emit an entry's rules from its facts (the slots' items as carried). */
function emitFromEntry(entry, exitSides = entry.exit_sides) {
    const p = entry.payload ?? {};
    const items = Object.fromEntries((entry.carried_rules?.locations ?? []).map((l) => [l.id, l.item ?? null]));
    return emitCloudberryRules(p.facts, { checks: p.checks, items, exitSides });
}

/**
 * Capability-vs-payload revalidation (the region-library validator's entryCapabilityCheck):
 * the payload is a resolved request + hash + facts, and the carried rules are exactly
 * what the facts emit.
 */
export function validateCloudberryLibraryEntry(entry) {
    const errors = [];
    const p = entry?.payload ?? {};
    if (!p.generate || typeof p.generate !== 'object') errors.push('payload.generate missing');
    else if (p.generate.reroll !== undefined) errors.push('payload.generate is a reroll search, not the resolved request');
    if (!/^[0-9a-f]{64}$/.test(p.docSha256 ?? '')) errors.push('payload.docSha256 is not 64 hex');
    if (!Array.isArray(p.facts?.pieceItems)) errors.push('payload.facts.pieceItems missing');
    if (!Array.isArray(p.checks) || p.checks.length === 0) errors.push('payload.checks missing or empty');
    for (const s of entry?.exit_sides ?? []) if (!SIDES.includes(s)) errors.push(`exit side '${s}' is not a grid side`);
    if (errors.length) return { errors };
    const cr = entry.carried_rules;
    if (!cr || typeof cr !== 'object') return { errors: ['carried_rules must be present'] };
    if ((cr.locations?.length ?? 0) !== entry.location_slots) {
        errors.push(`location_slots ${entry.location_slots} != carried_rules.locations count ${cr.locations?.length ?? 0}`);
    }
    let emitted;
    try { emitted = emitFromEntry(entry); } catch (err) { return { errors: [`facts do not emit: ${err.message}`] }; }
    const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);
    if (!same(emitted.locations, cr.locations)) errors.push('carried_rules.locations differ from the rules the facts emit');
    if (!same(emitted.exitPaths, cr.exitPaths)) errors.push('carried_rules.exitPaths differ from the rules the facts emit');
    if (!same(emitted.obstacleDefs, cr.obstacleDefs)) errors.push('carried_rules.obstacleDefs differ from the rules the facts emit');
    return { errors };
}

/** Capture a live Cloudberry region descriptor into a library entry. */
export function captureCloudberryLibraryEntry(region, meta = {}) {
    const pp = region?.playable_payload ?? {};
    const lib = region?.cloudberry ?? null;
    if (!pp.params?.generate || !lib?.facts) {
        throw new Error('captureLibraryEntry(cloudberry): region lacks params.generate / the cloudberry facts');
    }
    const exit_sides = [...region.exits.values()].map((e) => e.side).filter((s) => SIDES.includes(s));
    const entry = {
        entry_id: meta.entry_id ?? region.region_id,
        ...(meta.name ? { name: meta.name } : {}),
        substrate: CLOUDBERRY_SUBSTRATE_ID,
        exit_sides,
        payload: {
            ...(lib.args ? { args: lib.args } : {}),
            generate: pp.params.generate,
            docSha256: pp.params.docSha256,
            facts: lib.facts,
            checks: lib.checks,
        },
        carried_rules: null,
        location_slots: lib.checks.length,
    };
    const items = Object.fromEntries((region.extracted_rules?.locations ?? []).map((l) => [l.id, l.item ?? null]));
    const { locations, exitPaths, obstacleDefs } = emitCloudberryRules(lib.facts, { checks: lib.checks, items, exitSides: exit_sides });
    entry.carried_rules = { locations, exitPaths, obstacleDefs };
    return entry;
}

/** Zone rules for an entry placed on `exitSides` (items: per slot, in slot order). */
function zoneRulesFor(entry, region_id, exitSides, slotItems) {
    const p = entry.payload;
    const items = Object.fromEntries(p.checks.map((c, k) => [c.name, slotItems[k] ?? null]));
    const { locations, exitPaths, obstacleDefs, gateRules } = emitCloudberryRules(p.facts, { checks: p.checks, items, exitSides });
    const payload = buildCloudberryPayload(region_id, { generate: p.generate, docSha256: p.docSha256, checks: p.checks, gateRules });
    return { locations, exitPaths, obstacleDefs, payload };
}

function requireSides(entry, exitSides, what) {
    const offered = new Set(entry.exit_sides ?? []);
    for (const s of exitSides) {
        if (!offered.has(s)) {
            throw new Error(`${what}(cloudberry): slot needs side '${s}' but entry '${entry.entry_id}' `
                + `only offers [${(entry.exit_sides ?? []).join(',')}]`);
        }
    }
}

/**
 * Spiral content-source hook: the entry on the slot's sides (⊆ its own — every exit
 * leaves by the end door, so any side set works), its carried items kept. Draws no rng.
 */
export function instantiateCloudberryLibraryEntry(entry, ctx = {}) {
    const region_id = ctx.region_id ?? entry.entry_id;
    const exitSides = ctx.exitSides ?? entry.exit_sides;
    requireSides(entry, exitSides, 'instantiateLibraryEntry');
    const slotItems = (entry.carried_rules?.locations ?? []).map((l) => l.item ?? null);
    const zoneRules = zoneRulesFor(entry, region_id, exitSides, slotItems);
    const region = assembleZoneRegion({
        substrate: CLOUDBERRY_SUBSTRATE_ID, region_id, regionSize: ctx.regionSize, exitSides, zoneRules, zonePayload: {},
    });
    // What `captureLibraryEntry` needs back (the payload alone cannot say which piece a
    // check is in): a descriptor-only field, never serialized into a sidecar.
    region.cloudberry = {
        ...(entry.payload.args ? { args: entry.payload.args } : {}),
        facts: entry.payload.facts, checks: entry.payload.checks,
    };
    return region;
}

/** The game items a set of AP item names (a sphere gate) holds; other names hold none. */
function heldGameItems(gate = []) {
    return new Set((gate ?? []).map((name) => CLOUDBERRY_ITEMS_BY_AP_NAME[name]).filter(Boolean));
}

/**
 * The entry's check slots a player ENTERING with `entryGate` can reach: a slot in
 * piece k needs S_k (+ Jetpack on a Jetpack-hero level). Piece order. With NO entry
 * gate (`undefined`: a caller that is not sphere growth, e.g. the APWorld editor,
 * where every coin keeps its own emitted rule) every slot counts.
 */
function reachableSlots(entry, entryGate) {
    const checks = [...(entry.payload?.checks ?? [])].sort((a, b) => a.piece - b.piece);
    if (!Array.isArray(entryGate)) return checks;
    const held = heldGameItems(entryGate);
    const facts = entry.payload?.facts;
    return checks.filter((c) => requiredItems(facts, c.piece).every((it) => held.has(it)));
}

/**
 * Sphere content-source REFUSAL (P3a; the registry's `libraryEntryRefusal`, which the
 * engine's sphere fit and the APWorld editor's picker consult): why this entry is not
 * SOUND in this slot, or null. A sphere node's locations are free once inside
 * (requirement []), and a forward exit needs only its gate — but a library level is real
 * geometry: a coin in piece k needs S_k, and the end door needs S_last. So it refuses
 * when (1) fewer of its check slots are reachable with `ctx.entryGate` than the node has
 * locations, or (2) a forward exit's gate (`ctx.exitPlans[].gate`), with the entry gate,
 * misses an item of S_last. Both rules are SPHERE rules: they apply when the caller
 * passes `ctx.entryGate` (the engine's sphere source does; the APWorld editor does not,
 * and there every coin keeps its own emitted rule, so any slot is sound). Without this the sphere source picked by sides and slot count
 * alone, and the demo pack's sphere worlds were unwinnable (measured: the oracle "sphere
 * count mismatch: computed 1, planned 3", Victory never placed).
 */
export function cloudberryLibraryEntryRefusal(entry, ctx = {}) {
    const facts = entry?.payload?.facts;
    const id = entry?.entry_id;
    if (!facts?.pieceItems?.length) return `cloudberry: entry '${id}' has no document facts`;
    const sphere = Array.isArray(ctx.entryGate);
    const entryGate = ctx.entryGate ?? [];
    const wanted = (ctx.locationSpecs ?? []).length;
    const reachable = reachableSlots(entry, ctx.entryGate).length;
    if (reachable < wanted) {
        return `instantiateLibraryEntryForSpecs(cloudberry): entry '${id}' has ${reachable} check slot(s)`
            + `${sphere ? ` reachable with [${entryGate.join(', ')}] (of ${(entry.payload.checks ?? []).length})` : ''} `
            + `but the node needs ${wanted}`;
    }
    if (!sphere) return null;
    const last = exitItems(facts);
    for (const e of ctx.exitPlans ?? []) {
        const held = new Set([...heldGameItems(entryGate), ...heldGameItems(e.gate)]);
        const missing = last.filter((it) => !held.has(it));
        if (missing.length) {
            return `cloudberry: entry '${id}''s end door needs [${missing.map((m) => CLOUDBERRY_ITEM_NAMES[m] ?? m).join(', ')}], `
                + `which the ${e.side ?? '?'} exit's gate [${(e.gate ?? []).join(', ')}] and the entry gate `
                + `[${entryGate.join(', ')}] do not hold`;
        }
    }
    return null;
}

/**
 * Sphere content-source hook (requirement-aware): the node's items onto the check
 * slots the entry gate makes REACHABLE, in piece order (engine filler on the other
 * reachable ones; an unreachable coin is no location, an ordinary coin),
 * and the end door's REAL requirement as the forward exits' paths — the engine ANDs
 * its own gate onto them (buildSphereLibraryRegion), so the level's S_last is never
 * dropped for the overlay. The ENTRANCE side (`ctx.entranceSide`) is the start door's
 * way back: one free path (`backPortalGated` is false). Draws no rng.
 */
export function instantiateCloudberryLibraryEntryForSpecs(entry, ctx = {}) {
    const region_id = ctx.region_id ?? entry.entry_id;
    const exitSides = ctx.exitSides ?? [];
    const locationSpecs = ctx.locationSpecs ?? [];
    requireSides(entry, exitSides, 'instantiateLibraryEntryForSpecs');
    const slots = entry.payload?.checks ?? [];
    const reachable = reachableSlots(entry, ctx.entryGate);
    const refusal = cloudberryLibraryEntryRefusal(entry, { ...ctx, exitPlans: [] });
    if (refusal) throw new Error(refusal);
    // In a sphere slot a coin the entry gate does not reach is NOT a location: it stays an
    // ordinary coin. As a filler location it would need items the world may never have,
    // and AP's fill refuses the world (measured: "Could not access required locations …
    // region_4_2__coin66, region_4_2__coin84", the Falling Blocks / Clouds coins of
    // cb_falling_cloud in a Moving + Bouncy world). Outside sphere growth every slot stays.
    const used = Array.isArray(ctx.entryGate) ? reachable : slots;
    const usedEntry = used === slots ? entry : { ...entry, payload: { ...entry.payload, checks: slots.filter((c) => used.includes(c)) } };
    const itemOf = new Map(reachable.slice(0, locationSpecs.length).map((c, k) => [c.name, locationSpecs[k].item]));
    const slotItems = usedEntry.payload.checks.map((c) => (itemOf.has(c.name) ? itemOf.get(c.name) : (ctx.fillerItem ?? null)));
    const { locations, exitPaths, obstacleDefs, payload } = zoneRulesFor(usedEntry, region_id, exitSides, slotItems);
    if (ctx.entranceSide && exitPaths[ctx.entranceSide]) exitPaths[ctx.entranceSide] = [{ obstacles: [] }];
    return { locations, exitPaths, obstacleDefs, payload };
}

// ── Sphere-growth hooks (P2b; runner's are the model) ──

/** Enrich the engine's base zone specs with the world's Cloudberry knobs. */
export function buildCloudberryZoneSpecs(base, regionParams = {}) {
    const cloudberry = {};
    for (const k of Object.keys(DEFAULT_CLOUDBERRY_PROCGEN_PARAMS)) {
        if (regionParams[k] !== undefined) cloudberry[k] = regionParams[k];
    }
    return { ...base, cloudberry };
}

/**
 * Requirement-targeted level generation (the engine's generateRegionZoneGen contract).
 * Plans the level (synchronous, deterministic), then takes its generated result from
 * the cache; on a miss it YIELDS `{ type: 'attempt', …, await: <promise> }` — the
 * pipeline's asynchronous drivers await it — and reads the result after. A synchronous
 * caller cannot wait, so a miss there is refused by name; the generation it started keeps
 * running and is cached, so the same call made again once it is done succeeds (the APWorld
 * Editor's regenerate: press again).
 *
 * `ctx.entrance` (the engine's zone context): the region's way back and entry gate.
 */
export function* generateCloudberryZoneForSpecsGen(specs = {}, ctx = {}) {
    const plan = planCloudberryLevel(specs, ctx);
    let result = lookupCloudberryLevel(plan);
    if (!result) {
        const box = {};
        const promise = ensureCloudberryLevel(plan).then((r) => { box.result = r; return r; });
        yield {
            type: 'attempt', attempt: 1, attempts: 1, substrate: CLOUDBERRY_SUBSTRATE_ID,
            note: `generating Cloudberry level ${plan.region_id}`, await: promise,
        };
        result = box.result ?? lookupCloudberryLevel(plan);
        if (!result) {
            throw new Error(cloudberryGenerator()
                ? `cloudberry zone '${plan.region_id}': the level is being generated by the Cloudberry game page and `
                    + 'this caller drains synchronously, so it cannot wait — ask again once it is done (the generation '
                    + 'keeps running and is cached). The pipeline\'s asynchronous drivers (the panel, runSphereToStep, '
                    + 'sphere-step.js) wait on their own.'
                : `cloudberry zone '${plan.region_id}': no Cloudberry generator is installed — the browser installs a `
                    + 'hidden game page (cloudberryDemo); a headless caller installs scripts/procgen/cloudberrySite.mjs\'s '
                    + '(installHeadlessCloudberryGenerator).');
        }
    }
    if (result.refused) throw new Error(cloudberryRefusalMessage(plan, result));
    const zone = emitCloudberryZone(plan, result);
    return {
        locations: zone.locations,
        exitPaths: zone.exitPaths,
        obstacleDefs: zone.obstacleDefs,
        payload: cloudberryZonePayload(plan, result, zone),
    };
}

/** Synchronous form (drains the generator; refuses on a cache miss). */
export function generateCloudberryZoneForSpecs(specs = {}, ctx = {}) {
    const gen = generateCloudberryZoneForSpecsGen(specs, ctx);
    let r = gen.next();
    while (!r.done) r = gen.next();
    return r.value;
}

/**
 * Build the Cloudberry registry entry.
 */
export function createCloudberrySubstrateEntry({ id = CLOUDBERRY_SUBSTRATE_ID, label = 'Cloudberry Kingdom' } = {}) {
    const base = createFlashSubstrateEntry({
        id, label, iframeId: CLOUDBERRY_IFRAME_ID, sidecarFields: CLOUDBERRY_SIDECAR_FIELDS,
    });
    return Object.freeze({
        ...base,
        panelComponentType: CLOUDBERRY_PANEL_COMPONENT_TYPE,
        loadRegionEvent: CLOUDBERRY_LOAD_REGION_EVENT,
        iframeId: CLOUDBERRY_IFRAME_ID,

        // Exits are routed by side (the page's exit menu is a cross of the four sides);
        // the engine mints no tile for them.
        regionGeometry: REGION_GEOMETRY.SIDES,
        exitSides: CLOUDBERRY_EXIT_SIDES,

        // Flash's exits-Map world + the page's own vocabulary (exits by page side,
        // side portals, entrySide), derived at load and stripped again on save.
        deserializeWorld(payload) {
            const world = base.deserializeWorld(payload);
            world.params = pageParamsForWorld(world);
            return world;
        },
        serializeWorld(world, ...rest) {
            const out = base.serializeWorld(world, ...rest);
            if (out.params) {
                const params = { ...out.params };
                for (const k of PAGE_DERIVED_PARAMS) delete params[k];
                out.params = params;
            }
            return out;
        },

        getPlaybackController: () => _playbackProxy,

        // Loop mode (P3b): a SUMMARY substrate, as runner and noiz2sa — Record keeps a
        // visit's net result (checks, the exit taken, its play time), Playback applies it
        // at once, priced by TIME. The page reports its own clock (`setPlayClock(running,
        // {gameSeconds})`: physics steps / 60 since configure; stopped while the exit menu
        // is open or the tab hidden), so live play and the Bot block are charged per GAME
        // second played. The Bot walks queued checks (coins by name) and exits (by side;
        // the way back = the start door, item-free) through the page's bot.
        loopSupport: Object.freeze({
            queueActions: Object.freeze(['regionMove', 'locationCheck']),
            executeVia: 'solver',
            manual: true,
            customQueues: false,
            record: true,
            playback: true,
            instant: true,
            summaryRecording: true,
            playClock: true,
        }),

        victoryItem: CLOUDBERRY_VICTORY_ITEM,

        captureLibraryEntry: captureCloudberryLibraryEntry,
        instantiateLibraryEntry: instantiateCloudberryLibraryEntry,
        instantiateLibraryEntryForSpecs: instantiateCloudberryLibraryEntryForSpecs,
        // Sphere slots: an entry is refused where its real geometry is not sound (P3a).
        libraryEntryRefusal: cloudberryLibraryEntryRefusal,
        validateLibraryEntry: validateCloudberryLibraryEntry,

        libraryItems: CLOUDBERRY_LIBRARY_ITEMS,
        supportedFeatures: Object.freeze(['arbitrary_ap_locations', 'cloudberry_items']),
        // The ten items. Platform items gate as pieces; Jetpack in an exit gate rides
        // as a lock (and makes the child behind it a possible Jetpack-hero level).
        gateableItems: GATEABLE_ITEMS,

        // Sphere growth (P2b).
        buildZoneSpecs: buildCloudberryZoneSpecs,
        generateZoneForSpecs: generateCloudberryZoneForSpecs,
        generateZoneForSpecsGen: generateCloudberryZoneForSpecsGen,
        // Every forward exit leaves by the end door: equal platform parts only.
        canHostExitGates: canHostCloudberryExitGates,
        exitGateVeto: () => canHostCloudberryExitGates,
        gateHostingHint: cloudberryGateHostingHint,
        // The way back is the start door's (free; the payload's entrySide and the
        // side the player came in by).
        backPortalGated: () => false,
        // Every exit is offered at the end door's menu: no drift device needed.
        hostsSurplusExitsNatively: () => true,
        // A page boot (~10 s headless, once) + a reroll search per level (~1–3 s).
        generationCost: 'heavy',
        defaultProcgenParams: DEFAULT_CLOUDBERRY_PROCGEN_PARAMS,
        buildRegionParams: buildCloudberryRegionParams,
        renderProcgenParams: renderCloudberryProcgenParams,
        procgenParamsFromPayload: cloudberryProcgenParamsFromPayload,
    });
}

export const substrateRegistryEntry = createCloudberrySubstrateEntry();

if (!substrateRegistry.has(substrateRegistryEntry.id)) {
    substrateRegistry.register(substrateRegistryEntry);
}
