/**
 * seedlingDemo/procgenRng — THE GENERATOR'S DRAWS, seeded and deterministic.
 *
 * Seedling PROCGEN PoC arc, slice 1. ⚖ Kickoff §5: *no unseeded RNG anywhere
 * in the generator; the seed is part of the level's identity and its trace.*
 * So: no `Math.random`, no `Date.now`, no time, no ambient state — a seed in,
 * the same level out, byte for byte, on any machine and in any runtime.
 *
 * ── WHY THIS WRAPS `rng.js` INSTEAD OF ADDING ARITHMETIC ──────────────
 *
 * `rng.js` already carries a seeded, dependency-free, integer-exact generator
 * whose transcription is asserted against draws taken from the LIVE GAME
 * (`rng.test.js`). A second PRNG here would be a second stream nobody
 * compares — the one-of-everything law, applied to the smallest thing in the
 * arc. So the arithmetic is `SeedlingRng`'s and this file is vocabulary:
 * `nextInt`, `pick`, `shuffle`, and a `state` a trace row can carry.
 *
 * ⚠ **AND THE TWO STREAMS ARE NOT THE SAME STREAM, WHICH IS THE WHOLE
 * REASON FOR A SEPARATE FILE.** `SeedlingRng` models `Math.random()` *inside
 * the game* — a tape's `rng.seed` writes the generator the GAME will draw
 * from, and its absolute position is the page's whole history. A generation
 * seed is a name for a LEVEL and reaches no tape header. Same arithmetic,
 * different universes; a call site that took one for the other would be
 * seeding the game's rocks with the level's identity.
 *
 * ⛔ SEED 0 IS REFUSED. To `SeedlingRng`, 0 means "inherit the build's boot
 * seed" (`BOOT_SEED`, a `MOCK_DATE_TIME` constant) — a perfectly sensible
 * sentence about a tape and a lie about a level, whose seed is supposed to
 * BE its identity. A level generated at "seed 0" would be reproducible only
 * on artifacts built with the same clock stub.
 *
 * ⛔ NO NODE IMPORTS (see `atlasSource.js`).
 */

import { STATE_MAX, SeedlingRng } from './rng.js';

export class ProcgenRngError extends Error {
    constructor(message) {
        super(message);
        this.name = 'ProcgenRngError';
    }
}

const fail = (message) => { throw new ProcgenRngError(message); };

/** The seed range a level's identity may live in — `rng.js`'s own orbit. */
export const SEED_MIN = 1;
export const SEED_MAX = STATE_MAX;

/** A seed, checked. Returned so a caller can write `assertSeed(s)` inline. */
export function assertSeed(seed) {
    if (!Number.isInteger(seed) || seed < SEED_MIN || seed > SEED_MAX) {
        fail(`procgenRng: the seed must be an integer in [${SEED_MIN}, ${SEED_MAX}] — got `
            + `${JSON.stringify(seed)}. 0 is excluded on purpose: to the game's own `
            + 'generator it means "the build\'s boot seed", and a level\'s seed is its '
            + 'identity, not an inheritance.');
    }
    return seed;
}

/**
 * The generator's draws.
 *
 * ⚠ EVERY METHOD ADVANCES THE STREAM, including the ones that look like
 * queries. `state` does not — it is the readout a trace row carries so that
 * "this level was generated by these draws" is checkable after the fact
 * rather than asserted.
 */
export class ProcgenRng {
    constructor(seed) {
        this.seed = assertSeed(seed);
        this._rng = new SeedlingRng(seed);
        this.draws = 0;
    }

    /** The generator's position — a readout, NOT a draw. */
    get state() { return this._rng.state; }

    /** One draw in [0, 1). */
    next() {
        this.draws += 1;
        return this._rng.next();
    }

    /**
     * One draw in [0, n) — `Math.floor(random * n)`, the game's own idiom.
     *
     * ⚠ n must be a positive integer. `nextInt(0)` has no answer and the
     * silent one (0) is the index of a first element that is not there.
     */
    nextInt(n) {
        if (!Number.isInteger(n) || n <= 0) {
            fail(`procgenRng: nextInt needs a positive integer bound, got ${JSON.stringify(n)}.`);
        }
        this.draws += 1;
        return this._rng.nextIndex(n);
    }

    /** One draw in [lo, hi], both ends inclusive. */
    nextIntBetween(lo, hi) {
        if (!Number.isInteger(lo) || !Number.isInteger(hi) || hi < lo) {
            fail(`procgenRng: nextIntBetween needs integers with lo <= hi, got `
                + `${JSON.stringify(lo)}..${JSON.stringify(hi)}.`);
        }
        return lo + this.nextInt(hi - lo + 1);
    }

    /** One element of a non-empty list. */
    pick(items) {
        if (!Array.isArray(items) || items.length === 0) {
            fail('procgenRng: pick needs a non-empty array — an empty palette is a '
                + 'finding about the palette, not a draw that returns undefined.');
        }
        return items[this.nextInt(items.length)];
    }

    /**
     * A NEW array, shuffled — Fisher-Yates, descending, one draw per step
     * after the first.
     *
     * ⛔ IT DOES NOT MUTATE. The candidate order a step tries is derived from
     * the palette, and a shuffle in place would reorder the palette itself —
     * so the second step of the same run would draw from a table the first
     * step rewrote, and "same seed, same level" would hold only for one step.
     */
    shuffle(items) {
        if (!Array.isArray(items)) {
            fail(`procgenRng: shuffle needs an array, got ${JSON.stringify(items)}.`);
        }
        const out = [...items];
        for (let i = out.length - 1; i > 0; i -= 1) {
            const j = this.nextInt(i + 1);
            const tmp = out[i];
            out[i] = out[j];
            out[j] = tmp;
        }
        return out;
    }
}

/** `new ProcgenRng(seed)`, for call sites that read better as a function. */
export const rngFor = (seed) => new ProcgenRng(seed);
