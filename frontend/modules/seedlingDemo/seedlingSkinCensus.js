/** The classes still to draw, in census order (deduplicated): the next slice's list. */
export const CENSUS_REMAINING = Object.freeze([...new Set(SKIN_CENSUS.filter((r) => r.status === 'remaining').map((r) => r.as3))]);

/** The tags `levels` (atlas records, `{level, entities}`) place that `census` does not list, sorted. */
export function censusGaps(levels, census = SKIN_CENSUS) {
    const listed = new Set(census.map((r) => r.tag));
    const gaps = new Set();
    for (const l of levels) for (const e of l.entities ?? []) if (!listed.has(e.type)) gaps.add(e.type);
    return [...gaps].sort();
}
