/**
 * ⛓⛓ **LOGICAL SUB-REGION LINKS** (solver-walk §5.17; ⚖ the
 * user, 2026-10-03: the controller and the region binding learn a region move INSIDE a level — this amends
 * the level-granular binding, ruling 1 of 2026-07-27, for logical links).
 *
 * A region with a subgraph compiles to one AP region per sub-region (`level_0__r8c0`), all in ONE level,
 * and the rules join them with exits that carry a rule and no door: LOGICAL links. Nothing in the game
 * reports crossing one (no teleporter, no level change), so the binding needs two facts the sidecars do
 * not carry:
 *
 *   partition  which tile is in which sub-region — `atlases/seedling-subregion-partition.json`,
 *              generated by `scripts/procgen/make-seedling-subregion-partition.mjs` from each atlas's
 *              OWN analysis, keyed by `atlas_id` (`rules.region_atlas.atlas_id`);
 *   links      the rules' exits between two sub-regions of one level that no sidecar names (a sidecar
 *              exit is a door), each with its `access_rule`.
 *
 * Pure: no DOM, no fetch. `buildSubRegionMap` joins the two with the rules' sidecars; the binding asks
 * `subRegionAt` and `linkPath`.
 */

/** The partition document's file, beside the atlases (served path relative to `frontend/`). */
export const SUB_REGION_PARTITION_PATH = './modules/flashPanel/atlases/seedling-subregion-partition.json';

/** Why a rules file got no sub-region map (null = it got one, or it has no sub-regions at all). */
export const NO_PARTITION = (atlasId) => `the sub-region partition has no entry for atlas "${atlasId}" — `
    + 'regenerate it (scripts/procgen/make-seedling-subregion-partition.mjs); logical links are not '
    + 'recognised by position until then';

const sidecarsOf = (rules, player) => rules?.preset_sidecars?.[player] ?? {};

/**
 * The sub-region map for one rules file, or `{map: null, why}`.
 *
 * @param {object} o
 * @param {object} o.rules      the raw rules.json
 * @param {object} o.partition  the partition document
 * @param {string} [o.player]
 * @returns {{map: object|null, why: string|null}}
 *   map = `{atlasId, tileSize, alphabet, levels: Map<level, entry[]>, worlds: Map<regionId, payload>,
 *   links: Map<fromRegion, link[]>}`; an entry is `{region, level, origin, width, height, subs, rows}`,
 *   a link `{name, from, to, level, access_rule}`.
 */
export function buildSubRegionMap({ rules, partition, player = '1' }) {
    const worlds = new Map();
    for (const [region, sidecar] of Object.entries(sidecarsOf(rules, player))) {
        if (sidecar?.substrate !== 'flash_seedling' || !sidecar.playable_payload) continue;
        worlds.set(region, sidecar.playable_payload);
    }
    const subLevel = [...worlds.entries()].filter(([id]) => id.includes('__'));
    if (subLevel.length === 0) return { map: null, why: null };
    const atlasId = rules?.region_atlas?.atlas_id ?? null;
    const atlas = atlasId ? partition?.atlases?.[atlasId] : null;
    if (!atlas) return { map: null, why: NO_PARTITION(atlasId) };
    const alphabet = partition.alphabet;
    const levels = new Map();
    for (const [region, e] of Object.entries(atlas.regions ?? {})) {
        // Only the sub-regions the RULES carry (a compile may name none for a region the rules dropped).
        const subs = e.sub_regions.map((s) => (worlds.has(`${region}__${s}`) ? s : null));
        if (subs.every((s) => s === null)) continue;
        const entry = { region, level: e.level, origin: e.origin, width: e.width, height: e.height, subs, rows: e.rows };
        if (!levels.has(e.level)) levels.set(e.level, []);
        levels.get(e.level).push(entry);
    }
    const doors = new Set([...worlds.values()].flatMap((p) => (p.exits ?? []).map((x) => x.exitName)).filter(Boolean));
    const links = new Map();
    for (const [from, region] of Object.entries(rules?.regions?.[player] ?? {})) {
        const level = worlds.get(from)?.level;
        if (!Number.isInteger(level)) continue;
        for (const exit of region?.exits ?? []) {
            const to = exit.connected_region;
            if (doors.has(exit.name) || worlds.get(to)?.level !== level) continue;
            if (!links.has(from)) links.set(from, []);
            links.get(from).push({ name: exit.name, from, to, level, access_rule: exit.access_rule ?? null });
        }
    }
    return { map: { atlasId, tileSize: atlas.tile_size, alphabet, levels, worlds, links }, why: null };
}

/** Does `level` have a partition in `map` (i.e. sub-regions a position can tell apart)? */
export function levelHasSubRegions(map, level) {
    return !!map?.levels?.get(level)?.length;
}

/**
 * The sub-region (a compound AP region id) the pixel position `(x, y)` of `level` stands in, or null —
 * a wall, crossing material, a pruned pocket, or a level with no partition. Null is "no news".
 */
export function subRegionAt(map, level, x, y) {
    const entries = map?.levels?.get(level);
    if (!entries || !Number.isFinite(x) || !Number.isFinite(y)) return null;
    const tx = Math.floor(x / map.tileSize);
    const ty = Math.floor(y / map.tileSize);
    for (const e of entries) {
        const ch = e.rows[ty - e.origin[1]]?.[tx - e.origin[0]];
        if (!ch || ch === '.') continue;
        const sub = e.subs[map.alphabet.indexOf(ch)];
        if (sub) return `${e.region}__${sub}`;
    }
    return null;
}

/**
 * The shortest chain of links from `from` to `to` whose every link `open(link)` admits, or null.
 * `open` answers a door verdict (`{pass}`); a link it refuses is not walked through.
 *
 * @returns {{path: Array<{link, verdict}>}|{path: null, refused: Array<{link, verdict}>}}
 *   `refused` = the links out of reach that would have continued a route (for the warning's "needs").
 */
export function linkPath(map, from, to, open) {
    if (from === to) return { path: [] };
    const prev = new Map([[from, null]]);
    const queue = [from];
    const refused = [];
    for (let i = 0; i < queue.length; i += 1) {
        const at = queue[i];
        for (const link of map?.links?.get(at) ?? []) {
            if (prev.has(link.to)) continue;
            const verdict = open(link);
            if (!verdict.pass) { refused.push({ link, verdict }); continue; }
            prev.set(link.to, { at, link, verdict });
            if (link.to === to) {
                const path = [];
                for (let r = to; prev.get(r); r = prev.get(r).at) path.unshift({ link: prev.get(r).link, verdict: prev.get(r).verdict });
                return { path };
            }
            queue.push(link.to);
        }
    }
    return { path: null, refused };
}
