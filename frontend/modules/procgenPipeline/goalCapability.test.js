/**
 * ⚖ The user, 2026-10-11: "All substrates should support victory items. If they don't, then something is wrong."
 * This is the registry-level check that says which do not, by name.
 *
 * A SPIRAL substrate (procedural, or a zone source with `zoneCount`) holds the goal when a cell of it can hold pool
 * items (`spiralItemHolders`). A SPHERE substrate (one with a region realiser) holds it when its realiser places a
 * spec's item, so the check builds a one-location spec region of each and looks for the item.
 *
 * The known gaps are RULED, never discovered here: bounce, runner and Seedling atlas rooms ("Let's leave bounce,
 * runner, and Seedling for now"), and omsi ("Defer omsi", the design check of 2026-10-11). A substrate that joins a
 * gap list, or leaves one, fails this file until the list says so.
 */

import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, it, expect, beforeAll } from 'vitest';

import { REGISTRY_LIBRARIES } from '../../../scripts/procgen/reference/registry.mjs';
import { substrateRegistry } from '../shared/procgen/substrateRegistry.js';
import { regionRealiserKind, generationCostOf, GENERATION_COST } from '../procgenCore/substratePredicates.js';
import { spiralItemHolders, generateRegion } from './procgenPipelineEngine.js';
import { createRng } from '../shared/rng.js';
import { GOAL_ITEM } from '../procgenCore/goalItem.js';

const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..', '..', '..');

/** The ruled spiral gaps: zone sources whose regions hold no pool item, so never the goal. */
const KNOWN_SPIRAL_GOAL_GAPS = Object.freeze({
    bounce: '⚖ "leave bounce … for now": its zones come from authored tables (ability pickups only)',
    flash_seedling: '⚖ "leave … Seedling for now": a real atlas room offers only the locations it was marked with',
    omsi: '⚖ "Defer omsi": a town region has no slot for a planned item',
    runner: '⚖ "leave … runner … for now": its zones come from a generated table (ability pickups only)',
});

/** The ruled sphere gaps: spiral substrates with no region realiser, so sphere growth cannot place them at all. */
const KNOWN_SPHERE_GAPS = Object.freeze({
    omsi: '⚖ "Defer omsi": no spec path (`generateZoneForSpecs`)',
});

beforeAll(async () => {
    for (const rel of REGISTRY_LIBRARIES) {
        // eslint-disable-next-line no-await-in-loop
        await import(join(ROOT, rel));
    }
});

const isSpiral = (e) => typeof e.generateRegionCore === 'function' || typeof e.zoneCount === 'number';

describe('every spiral / sphere substrate can hold the goal, but the ruled known gaps', () => {
    it('spiral: the substrates whose cells hold no pool item are exactly the ruled gaps', () => {
        const { holders, gaps } = spiralItemHolders();
        expect(gaps).toEqual(Object.keys(KNOWN_SPIRAL_GOAL_GAPS).sort());
        expect(holders.length).toBeGreaterThan(0);
    });

    it('sphere: the spiral substrates sphere growth cannot realise are exactly the ruled gaps', () => {
        const unrealised = substrateRegistry.getAll().filter((e) => isSpiral(e) && regionRealiserKind(e) === null)
            .map((e) => e.id);
        expect(unrealised).toEqual(Object.keys(KNOWN_SPHERE_GAPS).sort());
    });

    it('sphere: every realiser places a spec\'s goal at a location (a one-location region with one exit)', () => {
        const checked = [];
        for (const e of substrateRegistry.getAll()) {
            if (regionRealiserKind(e) === null) continue;
            // A heavy substrate (runner) is generated by hand and by the box gates, not in vitest (⚖ 2026-09-16).
            if (generationCostOf(e) === GENERATION_COST.HEAVY) continue;
            e.prepareSphereGrowth?.({ itemPool: {}, quotas: { [e.id]: 1 }, params: {} });
            const region = generateRegion({
                substrate: e.id,
                region_id: 'goal_probe',
                size: { width: 10, height: 10 },
                entrances: [],
                exits: [{ side: 'E', requirement: [], counts: {} }],
                locations: [{ id: 'loc_0', item: GOAL_ITEM, requirement: [] }],
                itemLib: {},
                rng: createRng(1),
                params: {},
            });
            const held = (region.extracted_rules?.locations ?? []).map((l) => l.item);
            expect(held, `${e.id} built a region without the goal it was handed`).toContain(GOAL_ITEM);
            checked.push(e.id);
        }
        expect(checked).toEqual(expect.arrayContaining(['jta', 'maze', 'noiz2sa', 'text_adventure']));
    });
});
