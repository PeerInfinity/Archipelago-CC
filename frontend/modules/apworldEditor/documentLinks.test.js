/**
 * apworldEditor/documentLinks — **THE LINKS TAB'S ROWS** (APWORLD EDITOR HUB
 * slice H1).
 *
 * ⛓ The substrate half is checked TWICE and against two different things: once
 * against a hand-built fake registry (the shapes — a declarer, a non-declarer, a
 * malformed declaration), and once against the GENERATED capability matrix
 * (`procgenDocs/generated/registry.js`), which the reference generator builds by
 * importing the real substrate libraries. ⛔ The second is not a fixed point:
 * that file is output from the libraries, not from this one, so a substrate
 * that gains or drops `roomEditor` moves it and this row reds.
 */

import { describe, expect, it } from 'vitest';

import { REGISTRY } from '../procgenDocs/generated/registry.js';
import { DOCUMENT_LINKS, buildLinkRows, substrateEditorLinks } from './documentLinks.js';

/** ⛓ A registry-shaped stand-in: `getAll()` and nothing else is read. */
const fakeRegistry = (entries) => ({ getAll: () => entries });

describe('the substrate half is DERIVED', () => {
    it('⛓ one row per `roomEditor` declarer, and none for a substrate without one', () => {
        const rows = substrateEditorLinks(fakeRegistry([
            { id: 'maze', name: 'Maze', roomEditor: { kind: 'lab', page: 'maze', arm: 'set' } },
            { id: 'runner', name: 'Runner' },
            { id: 'bounce', name: 'Bounce', roomEditor: { kind: 'panel', open: () => {} } },
        ]));
        expect(rows.map((r) => r.substrate)).toEqual(['maze', 'bounce']);
        expect(rows.map((r) => r.editorKind)).toEqual(['lab', 'panel']);
    });

    it('⛓ a lab row names its page and arm and opens the lab HOST panel', () => {
        const [row] = substrateEditorLinks(fakeRegistry([
            { id: 'flash_seedling', roomEditor: { kind: 'lab', page: 'seedling', arm: 'edit' } },
        ]));
        expect(row.note).toContain('seedling lab page');
        expect(row.note).toContain('?source=edit');
        expect(row.target).toEqual({ kind: 'panel', panelId: 'procgenLabPanel' });
    });

    it('⛓ a panel row routes through the substrate resolver, not through a panel id', () => {
        const [row] = substrateEditorLinks(fakeRegistry([
            { id: 'bounce', roomEditor: { kind: 'panel', open: () => {} } },
        ]));
        expect(row.target).toEqual({ kind: 'substrateRoomEditor', substrate: 'bounce' });
    });

    /**
     * ⛔ A declaration `regionEditors.ROOM_EDITOR_KINDS` cannot open is
     * SOMEBODY'S BUG, and the row says so. A silent omission would read exactly
     * like "this substrate has no editor yet", which is a true sentence about
     * the wrong subject — `regionEditors.js`'s own refusal rule.
     */
    it('⛓⛓ an unopenable `kind` gets a NAMED row with no target, never silence', () => {
        const [row] = substrateEditorLinks(fakeRegistry([
            { id: 'weird', roomEditor: { kind: 'telepathy' } },
        ]));
        expect(row.target).toBeNull();
        expect(row.note).toContain('"telepathy"');
        expect(row.note).toContain('ROOM_EDITOR_KINDS');
    });

    it('⛓ a registry-shaped nothing is an empty list, not a throw', () => {
        expect(substrateEditorLinks(null)).toEqual([]);
        expect(substrateEditorLinks({})).toEqual([]);
        expect(substrateEditorLinks(fakeRegistry([]))).toEqual([]);
    });

    /**
     * ⛓⛓⛓ **AGAINST THE REAL LIBRARIES.** The capability matrix is generated by
     * importing every substrate library; its `roomEditor` row therefore names
     * exactly the substrates that declare one, today. Deriving the expected set
     * from it — never typing it — is what keeps this row true after H3/H4/H5.
     */
    it('⛓⛓ the derivation agrees with the GENERATED capability matrix', () => {
        const row = REGISTRY.rows.find((f) => f.name === 'roomEditor');
        const declarers = REGISTRY.columns
            .map((c, i) => (row.cells[i].present ? c.id : null))
            .filter(Boolean);
        const entries = REGISTRY.columns.map((c, i) => (row.cells[i].present
            ? { id: c.id, roomEditor: { kind: 'panel', open: () => {} } }
            : { id: c.id }));
        expect(substrateEditorLinks(fakeRegistry(entries)).map((r) => r.substrate))
            .toEqual(declarers);
        // ⛔ Non-vacuity: some substrates declare one and some do not, so the
        //    filter is doing work rather than passing everything through.
        expect(declarers.length).toBeGreaterThan(0);
        expect(declarers.length).toBeLessThan(REGISTRY.columns.length);
    });
});

describe('the document half is DATA, and it is complete', () => {
    it('⛓ every row the ⚖ named is present, each with a panel to open', () => {
        const ids = DOCUMENT_LINKS.map((r) => r.id);
        expect(ids).toEqual([
            'regionMarkingTool',
            'procgenPipelinePanel',
            'loopsCostDebuggerPanel',
            'editorCodeMirror6Panel',
            'editorPanel',
            'regionGraphPanel',
        ]);
        for (const row of DOCUMENT_LINKS) {
            expect(row.target, row.id).toMatchObject({ kind: 'panel' });
            expect(typeof row.target.panelId).toBe('string');
            expect(row.note.length).toBeGreaterThan(20);
        }
    });

    /**
     * ⛓ The ⚖ ruling, verbatim: *"We could add a button to open the region
     * graph, but I don't want a button in the region graph leading back to the
     * APWorld editor."* The asymmetry is deliberate and the row says so, so a
     * later reader does not "fix" it.
     */
    it('⛓ the region-graph row says out loud that it is ONE-WAY', () => {
        const graph = DOCUMENT_LINKS.find((r) => r.id === 'regionGraphPanel');
        expect(graph.note).toContain('ONE-WAY');
        expect(graph.note).toContain('no button back');
    });

    it('⛓ the applied-state editors WARN, because they do not see the working copy', () => {
        for (const id of ['loopsCostDebuggerPanel', 'editorCodeMirror6Panel', 'editorPanel']) {
            expect(DOCUMENT_LINKS.find((r) => r.id === id).note, id).toMatch(/[Aa]pplied|Apply/);
        }
    });
});

describe('the whole tab', () => {
    it('⛓ is the derived rows followed by the table, with unique ids', () => {
        const rows = buildLinkRows(fakeRegistry([
            { id: 'maze', roomEditor: { kind: 'lab', page: 'maze', arm: 'set' } },
        ]));
        expect(rows).toHaveLength(DOCUMENT_LINKS.length + 1);
        expect(rows[0].id).toBe('substrate:maze');
        expect(new Set(rows.map((r) => r.id)).size).toBe(rows.length);
    });
});
