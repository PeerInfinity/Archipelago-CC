/**
 * procgenCore/procgenRng — THE GENERATOR'S DRAWS: one vocabulary, one source
 * per substrate.
 *
 * CONSTRUCTIVE-MODE arc, slice 2 (`NewDocs/plans/seedling-constructive-mode-
 * kickoff.md` §3.2). ⚖ The PoC kickoff §5: *no unseeded RNG anywhere in the
 * generator; the seed is part of the level's identity and its trace.* So: no
 * `Math.random`, no `Date.now`, no time, no ambient state — a seed in, the same
 * level out, byte for byte, on any machine and in any runtime.
 *
 * ── ⛔ THE ARITHMETIC IS THE SOURCE'S; THIS FILE IS VOCABULARY ─────────
 *
 * `nextInt`, `pick`, `shuffle`, a `draws` counter and a `state` a trace row can
 * carry. The bit-mixing underneath is INJECTED, because the two substrates on
 * this loop already own two different, already-tested generators and a third
 * one here would be a stream nobody compares:
 *
 *   Seedling  `seedlingDemo/rng.js`'s `SeedlingRng` — the game's own
 *             `Math.random()`, whose transcription is asserted against draws
 *             taken from the LIVE GAME (`rng.test.js`).
 *   maze      `shared/rng.js`'s mulberry32 (`createRng`) — the generator every
 *             other maze-side producer already draws from.
 *
 * ⛔ **THERE IS NO DEFAULT SOURCE, AND THAT IS A DEPENDENCY FACT RATHER THAN
 * A TASTE.** The obvious default would be `SeedlingRng`; it would make
 * `procgenCore/` import from `seedlingDemo/`, and then `mazeRoom/procgenMaze.js`
 * → `procgenCore/procgenRng.js` → `seedlingDemo/rng.js` would drag the whole
 * Seedling graph into the maze's page by the shortest possible route — the
 * exact coupling this slice exists to remove (it is the mirror of slice 1's
 * `gridTiles.js`, where the shared submodule was reaching back into the outer
 * repo). So the source is REQUIRED and the substrate bindings supply it:
 * `seedlingDemo/procgenRng.js` and `mazeRoom/procgenRng.js` are each one small
 * file whose whole job is to name their source.
 *
 * ── THE SOURCE CONTRACT ───────────────────────────────────────────────
 *
 *   {
 *     name       string — what a refusal calls it
 *     assertSeed (seed) => seed, throwing BY NAME on a seed this generator
 *                cannot honestly carry (Seedling refuses 0; see its file)
 *     create     (seed) => { next(): float in [0,1),
 *                            nextIndex(n): int in [0,n),
 *                            get state(): the position a trace row carries }
 *   }
 *
 * ⛔ `nextIndex` IS THE SOURCE'S, not `Math.floor(next() * n)` computed here.
 * `SeedlingRng.nextIndex` is the GAME's own idiom and is transcribed from it;
 * re-spelling the multiply in this file would be a second cost model for the
 * one arithmetic that decides which template a step draws.
 *
 * ⚠ EVERY METHOD ADVANCES THE STREAM, including the ones that look like
 * queries. `state` does not — it is the readout a trace row carries so that
 * "this level was generated by these draws" is checkable after the fact rather
 * than asserted.
 *
 * ⛔ NO IMPORTS (see `levelGenerator.js`): this file is on both substrates'
 * browser path.
 */

export class ProcgenRngError extends Error {
    constructor(message) {
        super(message);
        this.name = 'ProcgenRngError';
    }
}

const fail = (message) => { throw new ProcgenRngError(message); };

/**
 * A source, checked once at construction. ⛔ It refuses rather than filling in
 * a missing member: a source with no `assertSeed` would accept every seed its
 * generator silently reinterprets, which is how a level's identity stops being
 * its seed.
 */
function assertSource(source) {
    if (!source || typeof source.create !== 'function'
        || typeof source.assertSeed !== 'function' || typeof source.name !== 'string') {
        fail('procgenRng: a ProcgenRng needs `{source: {name, assertSeed(seed), '
            + 'create(seed)}}`. ⛔ There is no default — a default would make procgenCore '
            + 'import from one substrate, and the other substrate\'s pages would carry '
            + 'that graph for nothing.');
    }
    return source;
}

/**
 * The generator's draws, over an injected source.
 *
 * @param {number} seed  the level's identity — validated by the SOURCE, which
 *   is the only thing that knows what its own generator does with a number.
 * @param {object} o.source see the file docblock's contract.
 */
export class ProcgenRng {
    constructor(seed, { source } = {}) {
        const s = assertSource(source);
        this.source = s.name;
        this.seed = s.assertSeed(seed);
        this._rng = s.create(this.seed);
        if (typeof this._rng?.next !== 'function' || typeof this._rng?.nextIndex !== 'function') {
            fail(`procgenRng: source "${s.name}" created a stream with no \`next\`/`
                + '`nextIndex`. Both are required: `next` is the float every carver reads '
                + 'and `nextIndex` is the generator\'s OWN index idiom, which this file '
                + 'deliberately does not re-spell.');
        }
        this.draws = 0;
    }

    /** The generator's position — a readout, NOT a draw. */
    get state() { return this._rng.state; }

    /** One draw in [0, 1). */
    next() {
        this.draws += 1;
        return this._rng.next();
    }

    /**
     * One draw in [0, n) — the source's own index idiom.
     *
     * ⚠ n must be a positive integer. `nextInt(0)` has no answer and the
     * silent one (0) is the index of a first element that is not there.
     */
    nextInt(n) {
        if (!Number.isInteger(n) || n <= 0) {
            fail(`procgenRng: nextInt needs a positive integer bound, got ${JSON.stringify(n)}.`);
        }
        this.draws += 1;
        return this._rng.nextIndex(n);
    }

    /** One draw in [lo, hi], both ends inclusive. */
    nextIntBetween(lo, hi) {
        if (!Number.isInteger(lo) || !Number.isInteger(hi) || hi < lo) {
            fail(`procgenRng: nextIntBetween needs integers with lo <= hi, got `
                + `${JSON.stringify(lo)}..${JSON.stringify(hi)}.`);
        }
        return lo + this.nextInt(hi - lo + 1);
    }

    /** One element of a non-empty list. */
    pick(items) {
        if (!Array.isArray(items) || items.length === 0) {
            fail('procgenRng: pick needs a non-empty array — an empty palette is a '
                + 'finding about the palette, not a draw that returns undefined.');
        }
        return items[this.nextInt(items.length)];
    }

    /**
     * A NEW array, shuffled — Fisher-Yates, descending, one draw per step
     * after the first.
     *
     * ⛔ IT DOES NOT MUTATE. The candidate order a step tries is derived from
     * the palette, and a shuffle in place would reorder the palette itself —
     * so the second step of the same run would draw from a table the first
     * step rewrote, and "same seed, same level" would hold only for one step.
     */
    shuffle(items) {
        if (!Array.isArray(items)) {
            fail(`procgenRng: shuffle needs an array, got ${JSON.stringify(items)}.`);
        }
        const out = [...items];
        for (let i = out.length - 1; i > 0; i -= 1) {
            const j = this.nextInt(i + 1);
            const tmp = out[i];
            out[i] = out[j];
            out[j] = tmp;
        }
        return out;
    }
}
