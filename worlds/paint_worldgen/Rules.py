def calculate_paint_percent_available(state: "CollectionState", player: int) -> bool:
    p = state.has('Pick Color', player)
    r = min(state.count('Progressive Color Depth (Red)', player), 7)
    g = min(state.count('Progressive Color Depth (Green)', player), 7)
    b = min(state.count('Progressive Color Depth (Blue)', player), 7)
    if not (p):
        r = min(r, 2)
        g = min(g, 2)
        b = min(b, 2)
    w = state.count('Progressive Canvas Width', player)
    h = state.count('Progressive Canvas Height', player)
    return (((((1 - (math.sqrt(((((((2 ** (7 - r)) - 1) ** 2) + (((2 ** (7 - g)) - 1) ** 2)) + (((2 ** (7 - b)) - 1) ** 2)) * 12)) / 765)) * min((400 + (w * state.multiworld.worlds[player].options.canvas_size_increment)), 800)) * min((300 + (h * state.multiworld.worlds[player].options.canvas_size_increment)), 600)) * state.multiworld.worlds[player].options.logic_percent) / 480000)


