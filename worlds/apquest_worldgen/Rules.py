"""
Access rules for APQuest WorldGen.

Auto-generated by world_generator using Rule Builder pattern.
The world class must inherit from RuleWorldMixin to use these rules.
"""

from typing import TYPE_CHECKING

from rule_builder import True_, False_, Has, HasAll

if TYPE_CHECKING:
    from worlds.AutoWorld import World


def set_rules(world: "World") -> None:
    """Set access rules for all locations and entrances.

    Uses world.set_rule() from RuleWorldMixin to properly resolve Rule Builder rules.
    """
    player = world.player
    multiworld = world.multiworld

    # Entrance rules
    world.set_rule(
        multiworld.get_entrance("Overworld to Bottom Right Room", player),
        Has("Sword")
    )

    world.set_rule(
        multiworld.get_entrance("Overworld to Top Left Room", player),
        Has("Key")
    )

    world.set_rule(
        multiworld.get_entrance("Right Room to Final Boss Room", player),
        Has("Top Left Room Button Pressed")
    )
    # Location rules
    world.set_rule(
        multiworld.get_location("Right Room Enemy Drop", player),
        Has("Sword")
    )

    world.set_rule(
        multiworld.get_location("Final Boss Defeated", player),
        HasAll('Shield', 'Sword')
    )
