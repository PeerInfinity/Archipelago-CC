from typing import Dict
from BaseClasses import MultiWorld, Region, Entrance
from .Locations import location_table, VVVVVVWorldGenLocation


# Region display names (hint text)
REGION_HINTS: Dict[str, str] = {
    "Menu": "Dimension VVVVVV",
}

def create_regions(multiworld: MultiWorld, player: int) -> None:
    """Create all regions, locations, and connections."""

    # Create all regions
    region_names = ["Menu", "Laboratory", "The Tower", "Space Station 2", "Warp Zone"]

    regions = {}
    for region_name in region_names:
        hint = REGION_HINTS.get(region_name)
        region = Region(region_name, player, multiworld, hint)
        regions[region_name] = region
        multiworld.regions.append(region)

    # Add locations to regions
    for location_name, location_data in location_table.items():
        region = regions[location_data.region]
        location = VVVVVVWorldGenLocation(
            player,
            location_name,
            location_data.location_id,
            region
        )

        # Apply location properties from location_data
        if location_data.progress_type is not None:
            location.progress_type = location_data.progress_type
        if not location_data.show_in_spoiler:
            location.show_in_spoiler = False

        region.locations.append(location)

    # Create entrances
    _create_entrance(regions["Menu"], regions["Laboratory"], "Menu -> Laboratory")
    _create_entrance(regions["Menu"], regions["The Tower"], "Menu -> The Tower")
    _create_entrance(regions["Menu"], regions["Space Station 2"], "Menu -> Space Station 2")
    _create_entrance(regions["Menu"], regions["Warp Zone"], "Menu -> Warp Zone")


def _create_entrance(source: Region, target: Region, name: str) -> Entrance:
    """Helper to create and connect an entrance."""
    entrance = Entrance(source.player, name, source)
    entrance.connect(target)
    source.exits.append(entrance)
    return entrance
