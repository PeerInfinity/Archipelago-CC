def _parse_entrance_name(entrance_name: str):
    """
    Parse entrance name to extract door information.

    Formats:
    - "Source to Target (through DoorRoom - DoorName)" -> (target, door_room, door_name)
    - "Sun Painting" (special case) -> (connected_region, connected_region, exit_name)
    """
    # Standard format: "X to Y (through Z - W)"
    match = re.match(r'^(.+?) to (.+?) \(through (.+?) - (.+?)\)$', entrance_name)
    if match:
        source, target, door_room, door_name = match.groups()
        return (target, door_room, door_name)

    return None


