def _parse_conditional(data: Mapping[str, Any], world_cls: type["RuleWorldMixin"]) -> "Rule[Any]":
    """
    Parse a conditional rule (typically from option filters).

    CC Format:
        {"type": "conditional", "test": {...}, "if_true": {...}, "if_false": {...}}

    This is complex because option filters in Rule Builder become conditionals in CC format.
    For simplicity, we parse the if_true branch since option filtering is typically
    handled at the world level.
    """
    from rule_builder.rules import True_

    test = data.get('test', {})
    if_true = data.get('if_true', {})
    if_false = data.get('if_false', {})

    # Check if if_false is just True (typical for option-filtered rules)
    if_false_is_true = (
        isinstance(if_false, dict) and
        if_false.get('type') == 'constant' and
        if_false.get('value') is True
    )

    if if_false_is_true:
        # This is an option-filtered rule - parse the if_true branch
        # The option filtering will be handled by world options at runtime
        if isinstance(if_true, dict):
            return parse_cc_rule(if_true, world_cls)

    # Complex conditional - for now, parse the if_true branch
    # A more complete implementation would handle the test condition
    logger.warning(f"Complex conditional rule, parsing if_true branch only")
    if isinstance(if_true, dict):
        return parse_cc_rule(if_true, world_cls)

    return True_()


def _parse_helper(data: Mapping[str, Any], world_cls: type["RuleWorldMixin"]) -> "Rule[Any]":
    """
    Parse a helper rule (game-specific or custom rules).

    CC Format:
        {"type": "helper", "name": "CustomRule", "args": [...]}

    Helper rules may have been converted from Rule Builder custom rules,
    or may be game-specific logic.
    """
    from rule_builder.rules import True_

    helper_name = data.get('name', 'Unknown')
    args = data.get('args', [])

    # Check for round-trip metadata
    if data.get('_converted_from_rule_builder'):
        # Try to restore the original Rule Builder format
        original_args = data.get('_original_args', {})
        try:
            rule_class = world_cls.get_rule_cls(helper_name)
            return rule_class.from_dict({
                'rule': helper_name,
                'options': [],
                'args': original_args
            }, world_cls)
        except (ValueError, KeyError, AttributeError):
            pass

    # Try to find a custom rule with this name
    try:
        rule_class = world_cls.get_rule_cls(helper_name)
        # Parse args - they may be constant-wrapped
        parsed_args = {}
        for i, arg in enumerate(args):
            if isinstance(arg, dict):
                if arg.get('type') == 'constant':
                    parsed_args[f'arg{i}'] = arg.get('value')
                else:
                    # Nested rule or complex value
                    parsed_args[f'arg{i}'] = arg
            else:
                parsed_args[f'arg{i}'] = arg

        return rule_class.from_dict({
            'rule': helper_name,
            'options': [],
            'args': parsed_args
        }, world_cls)
    except (ValueError, KeyError, AttributeError):
        logger.warning(f"Unknown helper rule '{helper_name}', treating as True")
        return True_()


def _parse_compare(data: Mapping[str, Any], world_cls: type["RuleWorldMixin"]) -> "Rule[Any]":
    """
    Parse a compare rule (comparison expression).

    CC Format:
        {"type": "compare", "left": {...}, "op": ">=", "right": {...}}

    Common patterns:
    - state.prog_items[player][item_name] >= count -> Has(item_name, count)
    - state.prog_items[player][item_name] > 0 -> Has(item_name, 1)

    For other patterns, we log a warning and return True_ as fallback.
    """
    from rule_builder.rules import Has, True_

    left = data.get('left', {})
    op = data.get('op', '')
    right = data.get('right', {})

    # Try to recognize the pattern: state.prog_items[player][item_name] >= count
    item_check = _try_parse_prog_items_check(left, op, right)
    if item_check is not None:
        return item_check

    # Unknown compare pattern - return True_ as fallback
    logger.warning(f"Unrecognized compare pattern, treating as True: {data}")
    return True_()


def _try_parse_prog_items_check(left: Any, op: str, right: Any) -> "Rule[Any] | None":
    """
    Try to parse a compare expression as a prog_items item check.

    Pattern: state.prog_items[player][item_name] OP count
    """
    from rule_builder.rules import Has

    # Check if right side is a constant (the count)
    if not isinstance(right, dict) or right.get('type') != 'constant':
        return None
    count = right.get('value', 0)

    # Handle >= operator (Has with count)
    if op == '>=':
        item_name = _extract_prog_items_item_name(left)
        if item_name is not None:
            return Has(item_name=item_name, count=count)

    # Handle > operator (Has with count + 1)
    elif op == '>':
        item_name = _extract_prog_items_item_name(left)
        if item_name is not None:
            return Has(item_name=item_name, count=count + 1)

    # Handle == operator with positive count
    elif op == '==' and count > 0:
        item_name = _extract_prog_items_item_name(left)
        if item_name is not None:
            # == count means "has exactly count", approximate as "has at least count"
            return Has(item_name=item_name, count=count)

    return None


def _extract_prog_items_item_name(expr: Any) -> str | None:
    """
    Extract the item name from a prog_items subscript expression.

    Pattern: state.prog_items[player][item_name]

    Returns the item_name string if the pattern matches, None otherwise.
    """
    # Expected structure:
    # {"type": "subscript", "value": {...}, "index": {"type": "constant", "value": "item_name"}}
    if not isinstance(expr, dict) or expr.get('type') != 'subscript':
        return None

    # Get the item name from the outer subscript index
    index = expr.get('index', {})
    if not isinstance(index, dict) or index.get('type') != 'constant':
        return None
    item_name = index.get('value')

    # Check that the inner expression is state.prog_items[player]
    inner = expr.get('value', {})
    if not isinstance(inner, dict) or inner.get('type') != 'subscript':
        return None

    # Check the innermost expression is state.prog_items
    innermost = inner.get('value', {})
    if not isinstance(innermost, dict) or innermost.get('type') != 'attribute':
        return None

    if innermost.get('attr') != 'prog_items':
        return None

    obj = innermost.get('object', {})
    if not isinstance(obj, dict) or obj.get('type') != 'name' or obj.get('name') != 'state':
        return None

    return item_name
