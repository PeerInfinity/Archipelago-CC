"""
Native CC (Archipelago-CC) format parsing for Rule Builder.

This module provides direct parsing of CC format JSON rules into Rule Builder
objects, eliminating the need for a separate conversion step.

CC Format Example:
    {"type": "item_check", "item": "Sword", "count": 1}

Rule Builder Format Example:
    {"rule": "Has", "options": [], "args": {"item_name": "Sword", "count": 1}}

The CC format is used in rules.json files generated by the exporter and consumed
by the frontend. This module allows Rule Builder to directly parse these rules.
"""

from __future__ import annotations

import logging
from collections.abc import Mapping
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from rule_builder.rules import Rule, RuleWorldMixin

logger = logging.getLogger(__name__)


def is_cc_format(data: Mapping[str, Any]) -> bool:
    """
    Detect if a rule dict is in CC format vs Rule Builder format.

    CC format uses 'type' key, Rule Builder uses 'rule' key.
    """
    return 'type' in data and 'rule' not in data


def parse_cc_rule(data: Mapping[str, Any], world_cls: type["RuleWorldMixin"]) -> "Rule[Any]":
    """
    Parse a CC format rule dict into a Rule Builder Rule object.

    Args:
        data: Rule dict in CC format (has 'type' key)
        world_cls: The world class for custom rule lookup

    Returns:
        A Rule object

    Raises:
        ValueError: If the rule type is unknown or cannot be parsed
    """
    # Import here to avoid circular imports
    from rule_builder.rules import (
        True_, False_, Has, HasAll, HasAny, HasAllCounts, HasAnyCount,
        HasFromList, HasFromListUnique, HasGroup, HasGroupUnique,
        And, Or, CanReachRegion, CanReachLocation, CanReachEntrance,
    )

    rule_type = data.get('type')

    if rule_type is None:
        raise ValueError(f"CC format rule missing 'type' field: {data}")

    # Dispatch based on type
    if rule_type == 'constant':
        return _parse_constant(data)

    elif rule_type == 'item_check':
        return _parse_item_check(data)

    elif rule_type == 'count_check':
        return _parse_count_check(data)

    elif rule_type == 'group_check':
        return _parse_group_check(data)

    elif rule_type == 'state_method':
        return _parse_state_method(data, world_cls)

    elif rule_type == 'and':
        return _parse_and(data, world_cls)

    elif rule_type == 'or':
        return _parse_or(data, world_cls)

    elif rule_type == 'can_reach':
        return _parse_can_reach(data)

    elif rule_type == 'location_check':
        return _parse_location_check(data)

    elif rule_type == 'can_reach_entrance':
        return _parse_can_reach_entrance(data)

    elif rule_type == 'conditional':
        return _parse_conditional(data, world_cls)

    elif rule_type == 'helper':
        return _parse_helper(data, world_cls)

    else:
        # Unknown type - log warning and return True_ as fallback
        logger.warning(f"Unknown CC rule type '{rule_type}', treating as True: {data}")
        return True_()


def _parse_constant(data: Mapping[str, Any]) -> "Rule[Any]":
    """Parse a constant rule: {"type": "constant", "value": true/false}"""
    from rule_builder.rules import True_, False_

    value = data.get('value')
    if value is True:
        return True_()
    elif value is False:
        return False_()
    else:
        # Non-boolean constants treated as True for logic purposes
        logger.warning(f"Non-boolean constant value '{value}', treating as True")
        return True_()


def _parse_item_check(data: Mapping[str, Any]) -> "Rule[Any]":
    """Parse an item_check rule: {"type": "item_check", "item": "Sword", "count": 1}"""
    from rule_builder.rules import Has

    item = data.get('item', '')
    count = data.get('count', 1)

    if isinstance(item, dict):
        # Complex item reference - log warning and use string representation
        logger.warning(f"Complex item reference in item_check: {item}")
        item = str(item)

    return Has(item_name=item, count=count)


