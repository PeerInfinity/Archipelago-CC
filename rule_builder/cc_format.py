def _parse_state_method(data: Mapping[str, Any], world_cls: type["RuleWorldMixin"]) -> "Rule[Any]":
    """
    Parse a state_method rule.

    Examples:
        {"type": "state_method", "method": "has_all", "args": [{"type": "constant", "value": ["Key1", "Key2"]}]}
        {"type": "state_method", "method": "has_any", "args": [{"type": "constant", "value": ["Sword", "Axe"]}]}
    """
    from rule_builder.rules import (
        Has, HasAll, HasAny, HasAllCounts, HasFromList, HasFromListUnique,
        HasGroup, HasGroupUnique, CanReachRegion, CanReachLocation, True_
    )

    method = data.get('method', '')
    args = data.get('args', [])

    def get_arg_value(index: int, default=None):
        """Extract value from argument, handling constant wrappers."""
        if index < len(args):
            arg = args[index]
            if isinstance(arg, dict) and arg.get('type') == 'constant':
                return arg.get('value', default)
            return arg
        return default

    if method == 'has':
        item = get_arg_value(0, '')
        count = get_arg_value(1, 1)
        return Has(item_name=item, count=count)

    elif method == 'has_all':
        items = get_arg_value(0, [])
        if isinstance(items, list):
            return HasAll(*items)
        return True_()

    elif method == 'has_any':
        items = get_arg_value(0, [])
        if isinstance(items, list):
            return HasAny(*items)
        return True_()

    elif method == 'has_all_counts':
        items = get_arg_value(0, {})
        if isinstance(items, dict):
            return HasAllCounts(item_counts=items)
        return True_()

    elif method == 'has_from_list':
        items = get_arg_value(0, [])
        count = get_arg_value(1, 1)
        if isinstance(items, list):
            return HasFromList(*items, count=count)
        return True_()

    elif method == 'has_from_list_unique':
        items = get_arg_value(0, [])
        count = get_arg_value(1, 1)
        if isinstance(items, list):
            return HasFromListUnique(*items, count=count)
        return True_()

    elif method == 'has_group':
        group = get_arg_value(0, '')
        count = get_arg_value(1, 1)
        return HasGroup(item_name_group=group, count=count)

    elif method == 'has_group_unique':
        group = get_arg_value(0, '')
        count = get_arg_value(1, 1)
        return HasGroupUnique(item_name_group=group, count=count)

    elif method == 'can_reach':
        name = get_arg_value(0, '')
        reach_type = get_arg_value(1, 'Region')
        if reach_type == 'Location':
            return CanReachLocation(location_name=name)
        else:
            return CanReachRegion(region_name=name)

    else:
        logger.warning(f"Unknown state_method '{method}', treating as True")
        return True_()


def _parse_and(data: Mapping[str, Any], world_cls: type["RuleWorldMixin"]) -> "Rule[Any]":
    """Parse an and rule: {"type": "and", "conditions": [...]}"""
    from rule_builder.rules import And, True_

    conditions = data.get('conditions', [])

    if not conditions:
        return True_()

    children = [parse_cc_rule(cond, world_cls) for cond in conditions]

    if len(children) == 1:
        return children[0]

    return And(*children)


def _parse_or(data: Mapping[str, Any], world_cls: type["RuleWorldMixin"]) -> "Rule[Any]":
    """Parse an or rule: {"type": "or", "conditions": [...]}"""
    from rule_builder.rules import Or, False_

    conditions = data.get('conditions', [])

    if not conditions:
        return False_()

    children = [parse_cc_rule(cond, world_cls) for cond in conditions]

    if len(children) == 1:
        return children[0]

    return Or(*children)


